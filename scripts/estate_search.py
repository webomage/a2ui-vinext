#!/usr/bin/env python3
"""Search the w0m estate correctly — per repo, bounded, and never silently empty (T406).

## Why this exists

Two measured traps make an ad-hoc search at the estate root worse than useless, because both
return **quickly and successfully** while looking at almost nothing.

**Trap 1 — the root repo excludes its own members.** `/Users/proto/Projects/@self/@wom/.git/info/exclude`
lists every `wom7*/` directory, so at the estate root:

    rg -n supabase          →     64 hits in 0.06s
    git grep -nI supabase   →     71 hits in 0.06s
    (per repo, summed)      →  5,268 hits

An agent that greps the root and finds nothing concludes the symbol does not exist anywhere. It is
the [[T135]]/[[T149]] vacuity shape with a search engine attached — and `.git/info/exclude` is
UNVERSIONED, so nothing in a diff would ever show you why.

⚠️ `--no-ignore-vcs` is NOT the fix. Measured at the root it returns **462,277 hits in 5.8s**,
because it walks `node_modules` in every repo. Neither default is right; the unit of search is a
REPO.

**Trap 2 — history, not the working tree, is what costs minutes.** Measured on wom7web:

    working tree (6,900 tracked files)   0.28s
    git grep over    20 commits          4.06s /  76,330 lines
    git grep over   100 commits         17.50s / 378,665 lines
    all 2,877 commits (extrapolated)    ~8 min / ~11M lines

`git grep <pat> $(git rev-list --all)` is the shape that pauses an agent for minutes and then buries
the console. This tool refuses to do it; `--history N` bounds it and says what it bounded.

## What the speedup guide is worth here — measured, not assumed

| technique | wom7web working tree | verdict |
|---|---|---|
| bare `git grep` | 0.282s | baseline |
| `LC_ALL=C git grep` | 0.123s | ✅ **2.3× — the one that pays.** Always on here |
| `+ -F` (fixed strings) | 0.121s | ➖ no measurable gain at this size; use for CORRECTNESS |
| `rg` | 0.098s | ➖ ~20% over `LC_ALL=C git grep`, not the order of magnitude the guide implies |
| `--threads=N` | — | ❌ git ≥ 2.26 already auto-threads (measured 344% CPU unset) |

🔴 `git config --global grep.patternType fixed` is REJECTED, and not on performance grounds: it
silently changes what every unflagged `git grep` MEANS, in every repo on the machine, including
other people's. Our gates pass `-E` explicitly and would survive it; the next ad-hoc regex would
not, and it would fail by matching nothing — quietly.

Usage:

    just search "getServerClient"              # every w0m repo, bounded
    just search "PUBLIC_SUPABASE" --repo web   # one repo
    just search "eyJ" --history 50             # last 50 commits, per repo, bounded
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys
import time
from pathlib import Path


def find_estate_root() -> Path:
    """Find the workspace root containing .tasks and .w0m/sdlc.json."""
    cur = Path(__file__).resolve()
    for parent in [cur] + list(cur.parents):
        if (parent / ".tasks").is_dir() and (parent / ".w0m").is_dir():
            return parent
        if (parent / ".git").exists() and (parent / "wom7web").is_dir():
            return parent
    return Path("/Users/proto/Projects/@self/@wom")


ESTATE = find_estate_root()

# The repos w0m OWNS. `wom7pr` and `k7` hold vendored forks (orca alone is larger than the entire
# rest of the estate) and `wom7mlx` nests its real repo one level down — including them by default
# would make every search slower and noisier for results nobody asked for. `--all` opts in.
OWNED = ("root", "wom7web", "wom7api", "wom7func", "wom7ext", "wom7sec", "wom7skills")
VENDORED = ("wom7pr", "wom7mlx", "k7")

# Explicit top-level pathspecs when searching the `@wom` root repo (`root == ESTATE`) with no `--path`,
# so searching `"root"` is fast, deterministic, and never traverses nested repos even if `.git/info/exclude` differs.
ROOT_PATHS = (
    "scripts/",
    "project/",
    "docs/",
    ".tasks/",
    "justfile",
    "AGENTS.md",
    "CLAUDE.md",
)

# Generated trees that are tracked in at least one repo and would otherwise dominate every result.
NOISE = (
    ":!*graphify-out/*",
    ":!*/reports/*",
    ":!*.lock",
    ":!*/state-archive/*",
    # Generated by the pre-commit hook: one 261-line <script> tag carrying EVERY ticket body, so it
    # matches almost any pattern and drowns the real hits.
    ":!*STATUS-DASHBOARD.html",
)

DEFAULT_CAP = 200


def _resolve_repo_arg(r: str) -> str:
    """Normalise a `--repo` argument (`root`/`@wom`/`w0m`, short `web`, or full `wom7web`)."""
    if r in ("root", "@wom", "w0m"):
        return "root"
    if r.startswith(("wom7", "k7")):
        return r
    return f"wom7{r}"


def repo_root(name: str) -> Path | None:
    """The git root for a repo name, or None when there is nothing searchable there."""
    d = ESTATE if name == "root" else ESTATE / name
    return d if (d / ".git").exists() else None


def search_tree(root: Path, pattern: str, fixed: bool, paths: list[str]) -> tuple[list[str], float]:
    """`git grep` over the working tree, with the two flags that are load-bearing here.

    🔑 `--no-pager` is not style. `git grep` attaches a pager when stdout is a terminal, and an
    agent shell that gets one hangs until its own timeout and then dumps everything at once — the
    exact symptom that started T406. The wom7api justfile already carried this warning at one call
    site (`check-guardrails`) and not at the other (`tech-debt`).
    🔑 `LC_ALL=C` is the measured 2.3× win: byte matching instead of UTF-8 collation.
    """
    cmd = ["git", "--no-pager", "grep", "-nI"]
    cmd.append("-F" if fixed else "-E")
    effective_paths = list(paths) if paths else (list(ROOT_PATHS) if root == ESTATE else [])
    cmd += [pattern, "--"] + effective_paths + list(NOISE)
    env = dict(os.environ, LC_ALL="C")
    t = time.perf_counter()
    p = subprocess.run(cmd, cwd=root, env=env, capture_output=True, text=True, timeout=120)
    # rc 1 == "no matches", which is a RESULT. rc >1 is a failure and must not read as zero hits.
    if p.returncode > 1:
        raise RuntimeError(p.stderr.strip() or f"git grep exited {p.returncode}")
    return [l for l in p.stdout.splitlines() if l], time.perf_counter() - t


def search_history(root: Path, pattern: str, fixed: bool, depth: int) -> tuple[list[str], float]:
    """The same search over the last `depth` commits — bounded, because unbounded is ~8 minutes."""
    revs = subprocess.run(["git", "rev-list", "--all", f"-n{depth}"], cwd=root,
                          capture_output=True, text=True, timeout=120).stdout.split()
    if not revs:
        return [], 0.0
    # ⚠️ The same NOISE pathspec as the working-tree search. Omitting it here was a real bug in the
    # first version: a history search returned the generated STATUS-DASHBOARD.html once per commit,
    # so the result grew with the depth bound rather than with the code.
    effective_paths = list(ROOT_PATHS) if root == ESTATE else []
    cmd = (["git", "--no-pager", "grep", "-nI", "-F" if fixed else "-E", pattern]
           + revs + ["--"] + effective_paths + list(NOISE))
    env = dict(os.environ, LC_ALL="C")
    t = time.perf_counter()
    p = subprocess.run(cmd, cwd=root, env=env, capture_output=True, text=True, timeout=600)
    if p.returncode > 1:
        raise RuntimeError(p.stderr.strip() or f"git grep exited {p.returncode}")
    return [l for l in p.stdout.splitlines() if l], time.perf_counter() - t


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("pattern")
    ap.add_argument("--repo", action="append", help="repo short name (root, web, api, …) or full (wom7web). Repeatable.")
    ap.add_argument("--all", action="store_true", help="include the vendored forks (wom7pr, wom7mlx, k7)")
    ap.add_argument("-F", "--fixed", action="store_true", help="literal string, not a regex")
    ap.add_argument("--history", type=int, metavar="N", help="also search the last N commits per repo")
    ap.add_argument("--cap", type=int, default=DEFAULT_CAP, help=f"max lines printed per repo (default {DEFAULT_CAP})")
    ap.add_argument("--path", action="append", default=[], help="pathspec to restrict to, e.g. 'apps/**'. Repeatable.")
    args = ap.parse_args(argv)

    names = list(OWNED) + (list(VENDORED) if args.all else [])
    if args.repo:
        want = {_resolve_repo_arg(r) for r in args.repo}
        names = [n for n in names + list(VENDORED) if n in want]
        if not names:
            print(f"[BLOCKED] no such repo in {ESTATE}: {', '.join(sorted(want))}")
            return 2

    total = 0
    unmeasurable: list[str] = []
    for name in names:
        root = repo_root(name)
        if root is None:
            # 🔴 Its own state, never folded into "0 hits" — see the module docstring.
            target = ESTATE if name == "root" else ESTATE / name
            unmeasurable.append(f"{name}: no git repo at {target}")
            continue
        try:
            hits, secs = search_tree(root, args.pattern, args.fixed, args.path)
        except (RuntimeError, subprocess.TimeoutExpired) as e:
            unmeasurable.append(f"{name}: {e}")
            continue
        total += len(hits)
        if hits:
            shown = hits[: args.cap]
            print(f"\n── {name} — {len(hits)} hit(s) in {secs:.2f}s")
            for line in shown:
                print(f"   {line[:200]}")
            if len(hits) > len(shown):
                print(f"   … {len(hits) - len(shown)} more line(s) NOT SHOWN (--cap {args.cap})")

        if args.history:
            try:
                h, hs = search_history(root, args.pattern, args.fixed, args.history)
            except (RuntimeError, subprocess.TimeoutExpired) as e:
                unmeasurable.append(f"{name} history: {e}")
                continue
            if h:
                print(f"\n── {name} HISTORY (last {args.history} commits) — {len(h)} hit(s) in {hs:.1f}s")
                for line in h[: args.cap]:
                    print(f"   {line[:200]}")
                if len(h) > args.cap:
                    print(f"   … {len(h) - args.cap} more line(s) NOT SHOWN (--cap {args.cap})")

    scope = ", ".join(names)
    print(f"\n── {total} hit(s) across {len(names)} repo(s): {scope}")
    if unmeasurable:
        # Fail loudly: a repo that could not be searched is not a repo with no matches.
        print(f"\n[BLOCKED] {len(unmeasurable)} repo(s) COULD NOT BE SEARCHED — this is not 'no hits':")
        for u in unmeasurable:
            print(f"   - {u}")
        return 1
    if total == 0:
        print("   (a real zero: every listed repo was searched and matched nothing)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
