# ── retention (T174) ─────────────────────────────────────────────────────────
#
# WHY THIS LIVES HERE AND NOT IN A CONSTANT
#     Every value below is read from `.w0m/sdlc.json → state_surface.retention`. That is a
#     deliberate constraint, not a preference: on 2026-08-07 `sdlc.json` was found to have
#     attributed both Obsidian MCP ports to the wrong plugin FOR TWELVE DAYS because the
#     attribution had been INFERRED rather than recorded. A governance file that disagrees with
#     reality is worse than none, so this module holds no policy of its own and fails loudly when a
#     declared key is missing rather than falling back to a built-in default (which would make the
#     declared policy a fiction).
#
# WHY ROTATION IS SAFE AT ALL
#     Nothing in the estate parses STATE.md section ids — `grep '### 0\|0y'` over
#     project/scripts/*.py and .husky/* returns zero. Every consumer is marker-based (BEGIN/END +
#     the DATA payload) or shells out to `just state-check`. So this is FILE MOTION, not a parser
#     change. Re-verify that before extending the patterns; a recorded measurement is not a
#     permanent one.

class RetentionConfigError(RuntimeError):
    """A declared retention key is missing or malformed. Never swallowed into a default."""


SDLC_JSON = MONO_ROOT / ".w0m" / "sdlc.json"
_REQUIRED_RETENTION_KEYS = (
    "archive_dir", "archive_pattern", "max_lines", "max_bytes",
    "rotate_patterns", "never_rotate", "disposition_record",
)


def retention_cfg() -> dict:
    """Read + validate the retention policy. Raises RetentionConfigError naming the bad key."""
    try:
        cfg = json.loads(SDLC_JSON.read_text())
    except FileNotFoundError as e:
        raise RetentionConfigError(f"{SDLC_JSON} not found — no declared retention policy") from e
    except json.JSONDecodeError as e:
        raise RetentionConfigError(f"{SDLC_JSON} is not valid JSON: {e}") from e
    r = (cfg.get("state_surface") or {}).get("retention")
    if not isinstance(r, dict):
        raise RetentionConfigError(
            "`state_surface.retention` is absent from .w0m/sdlc.json — T174 requires the policy to "
            "be DECLARED, so there is deliberately no built-in default to fall back on")
    for k in _REQUIRED_RETENTION_KEYS:
        if k not in r:
            raise RetentionConfigError(f"`state_surface.retention.{k}` is not declared")
    for k in ("max_lines", "max_bytes"):
        if not isinstance(r[k], int) or isinstance(r[k], bool) or r[k] <= 0:
            raise RetentionConfigError(
                f"`state_surface.retention.{k}` must be a positive integer, got {r[k]!r}")
    for k in ("rotate_patterns", "never_rotate"):
        if not isinstance(r[k], list) or not r[k]:
            raise RetentionConfigError(
                f"`state_surface.retention.{k}` must be a NON-EMPTY list — an empty pattern set "
                "makes every downstream comparison vacuous, which is the exact shape this estate "
                "has shipped four times (T127, T130, T135 docs-check, the wom7md hook)")
    return r


_DETAILS_OPEN = re.compile(r"^\s*<details[ >]")
_DETAILS_CLOSE = re.compile(r"^\s*</details>\s*$")
_HEADING = re.compile(r"^#{2,3} ")


def sections(text: str) -> list[dict]:
    """Split the prose into heading-delimited sections, OUTSIDE the managed block.

    ⚠️ THE `<details>` WRAPPERS ARE INCONSISTENT AND THIS IS WHERE A NAIVE SPLIT CORRUPTS THE FILE.
    Five superseded blocks sit inside `<details><summary>…</summary>` … `</details>`; two others
    (2026-08-06 and 2026-08-01) are bare. Since a raw heading→next-heading range ends just before
    the NEXT heading, it swallows the `<details>` opener that belongs to the next section — deleting
    that range would strip the following block's wrapper and leave an orphaned `</details>`.

    So a range is trimmed of trailing openers (they belong forward) and extended backwards over its
    own opener. `rotate()` then asserts tag balance on every chunk it removes, because "the markdown
    still looks fine" is not a proof.
    """
    lines = text.split("\n")
    body_start = 0
    if END in text:
        body_start = text[: text.index(END)].count("\n") + 1

    idx = [i for i, l in enumerate(lines) if i >= body_start and _HEADING.match(l)]
    out: list[dict] = []
    for k, i in enumerate(idx):
        end = idx[k + 1] if k + 1 < len(idx) else len(lines)
        # trailing `<details>` openers belong to the NEXT section, not this one
        while end - 1 > i and (_DETAILS_OPEN.match(lines[end - 1]) or not lines[end - 1].strip()):
            if _DETAILS_OPEN.match(lines[end - 1]):
                end -= 1
            elif end - 2 > i and _DETAILS_OPEN.match(lines[end - 2]):
                end -= 1          # the blank line separating them goes forward too
            else:
                break
        # absorb this section's OWN opener, sitting just above the heading
        start = i
        j = i - 1
        while j > body_start and not lines[j].strip():
            j -= 1
        if j > body_start and _DETAILS_OPEN.match(lines[j]):
            start = j
        out.append({
            "heading": lines[i],
            "start": start,          # 0-based, inclusive — includes an absorbed opener
            "hstart": i,
            "end": end,              # 0-based, exclusive
            "bytes": len("\n".join(lines[i:end])),
        })
    return out


def _slug(heading: str) -> str:
    """`### 0y12. superseded pickup block — 2026-07-28 — **T151 AC1 DONE …**` → `0y12-t151-ac1-done`.

    The section id (or the parenthetical qualifier, for the ⭐ blocks) leads, because SEVEN blocks
    share the date 2026-07-26 and a date-only name would collide six times over.
    """
    h = heading.lstrip("# ").strip()
    lead = ""
    m = re.match(r"(0y\d*|0[a-z])\.", h)
    if m:
        lead = m.group(1)
    elif "PICK UP HERE" in h:
        q = re.search(r"—\s*\d{4}-\d{2}-\d{2}\s*\(([^)]{1,32})\)", h)
        # 🔴 The qualifier is interpolated into a FILENAME, so it gets the same alphanumeric
        # reduction the tail gets. It used to be taken verbatim from `[^)]{1,32}`, which admits
        # `/` and `..` — a heading reading `(../../evil)` yielded `…-pickup-../../evil-x.md`, and
        # `arch_dir / name` would then write OUTSIDE the archive directory. Found in T174's
        # security gate. The input is a repo file rather than a remote request, so this was never
        # remotely exploitable — but STATE.md is agent-written and its Obsidian vault is mounted
        # read-WRITE over MCP (T174's own recorded risk 3), so "only we write it" is thinner than
        # it sounds. It had also already misfired benignly: `(later session)` produced a filename
        # containing a SPACE, which is still on disk as 2026-07-31-pickup-later session-….md.
        lead = ("pickup-" + "-".join(re.findall(r"[A-Za-z0-9]+", q.group(1)))) if q else "pickup"
    tail = ""
    b = re.search(r"\*\*(.+?)\*\*", h, re.S)
    if b:
        tail = b.group(1)
    else:
        parts = h.split("—")
        tail = parts[-1] if parts else h
    words = re.findall(r"[A-Za-z0-9]+", tail)[:6]
    s = "-".join([lead, *words]).lower()
    s = re.sub(r"-{2,}", "-", s).strip("-")
    # Belt and braces: whatever the branches above produced, a slug may never carry a path
    # separator or a parent-directory hop. Asserted rather than assumed, because this string
    # becomes a path and the cost of being wrong is a write outside the archive.
    if "/" in s or "\\" in s or ".." in s:
        raise RetentionConfigError(
            f"refusing to build an archive filename from heading {heading[:60]!r}: the derived "
            f"slug {s!r} contains a path separator or parent hop")
    return s[:72] or "section"


def _date_of(heading: str) -> str:
    m = re.search(r"(\d{4}-\d{2}-\d{2})", heading)
    return m.group(1) if m else "0000-00-00"


def section_key(heading: str) -> str:
    """A stable key for a section — its ID where it has one, else its slug.

    WHY AN ID MATTERS MORE THAN IT LOOKS: ten files carry FOURTEEN inbound references of the form
    "`STATE.md` §0t" (T138, T139, T136, T137, T127, T126, T135, T147, T172, TASKS.md). Rewriting all
    of them would be churn with a real chance of error, so instead the id survives INTO THE ARCHIVE
    FILENAME and into the disposition record, and a reader who follows "§0t" can still resolve it.
    Preserving addressability was not optional — a reference that no longer resolves is the same
    lesson-lost failure as deleting the section.
    """
    # LEVEL MATTERS, and finding out why cost a collision: `## 0. Orient (2 min)` and
    # `### 0. T127 Phase 2` both yield the bare id `0`. Every one of the fourteen inbound `§…`
    # references points at a LEVEL-3 section, and no other file references a level-2 heading by id,
    # so ids are reserved for `###` and level-2 sections key on their slug. A key that is not unique
    # is not a key.
    h = heading.lstrip("# ").strip()
    if heading.startswith("### "):
        m = re.match(r"(0y\d*|0[a-z]|1[a-z]|\d+)\.", h)
        if m:
            return m.group(1)
    return _slug(heading)


def read_disposition(path: Path) -> dict[str, tuple[str, str]]:
    """Parse the disposition record → {section_key: (disposition, reason)}.

    The record is EXECUTABLE, not documentary: `rotate()` moves a judged section only because a row
    here says to. That inverts the usual risk — a triage decision cannot be applied without first
    being written down where a reviewer sees it in a diff.
    """
    if not path.exists():
        return {}
    out: dict[str, tuple[str, str]] = {}
    for line in path.read_text().split("\n"):
        # ⚠️ The value class must cover EVERY name in DISPOSITIONS, and the obvious `[a-z-]+` does
        # not: `promoted-to-CLAUDE.md` carries capitals and a dot, so it silently failed to parse
        # and its section read back as having NO row at all. Fail-closed (an unaccounted section is
        # a hard error, so nothing could be lost) but wrong twice over — the tool could not express
        # one of its own four states, and the error it raised named the opposite of the problem.
        # Found in T174's review gate. Keep this pattern and DISPOSITIONS in lockstep; the
        # round-trip probe in test_state_doctor.py asserts all four survive.
        m = re.match(r"\|\s*`([^`]+)`\s*\|\s*([A-Za-z][A-Za-z.\-]*)\s*\|\s*(.*?)\s*\|\s*$", line)
        if m and m.group(2) in DISPOSITIONS:
            out[m.group(1)] = (m.group(2), m.group(3))
    return out


DISPOSITIONS = ("archived", "promoted-to-auto-memory", "promoted-to-CLAUDE.md", "kept-live")


# T257 AC2 — the handoff marker IS the glyph today, so state rotation stops finding the
# current block without it. A bracketed text form is accepted alongside, so STATE.md can be
# de-emojified without the rotation silently losing track of which block is live.
PICKUP_RE = re.compile(r"^#{2,3} (?:⭐|\[PICKUP\]) (?:\(was\) )?PICK UP HERE")


def rotate(apply: bool = True) -> tuple[int, list[str], list[str]]:
    """Move mechanically-identifiable dead sections into the archive. Returns (moved, files, notes).

    Contract (T174 AC1):
      * VERBATIM — content is moved, never transformed. This is a SECURITY clause: several sections
        are the only record of credential incidents, and a "helpful" rewrite of one would be an
        unreviewed edit to a security record.
      * The managed block is never touched (`sections()` starts below END; `never_rotate` re-asserts
        it, so the guarantee does not rest on one mechanism).
      * IDEMPOTENT — a second run finds nothing and leaves the file byte-identical.
      * An empty candidate set is REPORTED as such, not passed off as a clean sweep.
    """
    cfg = retention_cfg()
    notes: list[str] = []
    if not STATE_MD.exists():
        raise RetentionConfigError(
            f"{STATE_MD} does not exist — refusing to report a clean rotation over a missing "
            "handoff surface")
    text = STATE_MD.read_text()
    if not text.strip():
        raise RetentionConfigError(
            f"{STATE_MD} is empty — a zero-byte file is trivially 'nothing to rotate', which is the "
            "vacuous pass this check exists to refuse")

    rotate_res = [re.compile(p) for p in cfg["rotate_patterns"]]
    never_res = [re.compile(p) for p in cfg["never_rotate"] if p.startswith("^")]

    disp = read_disposition(STATE_MD.parent / cfg["disposition_record"])
    lines = text.split("\n")

    # 🔴 SUPERSEDED PICKUP BLOCKS, IDENTIFIED BY DATE — not by a rename nobody performs.
    # The `rotate_patterns` expect `### ⭐ (was) PICK UP HERE`, a heading something used to rewrite:
    # 17 archived files carry that form and STATE.md today carries ZERO. Meanwhile `never_rotate`
    # protects `^## ⭐ PICK UP HERE`, which shields the superseded ones too — so the file held FOUR
    # pickup blocks (two both claiming "(LATEST)") and rotation could never fire. Measured
    # 2026-08-19 at 94% of the byte cap with `state-rotate` reporting an empty candidate set.
    # ⇒ Only the NEWEST pickup block is current; every older one is dead by definition, because
    # writing a new one is what supersedes it. That is mechanical and needs no human step.
    # ⚠️ Ordering is by the DATE IN THE HEADING, not file position — a block appended out of order
    # must not silently become "current".
    pickup = [(m, d) for m in PICKUP_RE.finditer(text)
              if (d := (re.search(r"20\d{2}-\d{2}-\d{2}", m.group(0)) or [None]) )]
    pickup_dates = []
    for s in sections(text):
        if PICKUP_RE.match(s["heading"]):
            dm = re.search(r"20\d{2}-\d{2}-\d{2}", s["heading"])
            pickup_dates.append((dm.group(0) if dm else "", s["heading"]))
    superseded_pickups: set[str] = set()
    if len(pickup_dates) > 1:
        newest = max(pickup_dates, key=lambda t: t[0])[1]
        superseded_pickups = {h for _, h in pickup_dates if h != newest}

    cand: list[dict] = []
    for s in sections(text):
        h = s["heading"]
        if h in superseded_pickups:
            cand.append({**s, "why": "superseded-pickup"})
            continue
        if any(r.match(h) for r in never_res) or ARCH_BEGIN in h or "Archived history" in h:
            continue
        # Two independent reasons to move a section, and keeping them separate is the point:
        #   MECHANICAL — its shape says it is dead (a superseded pickup block announces itself)
        #   JUDGED     — a human recorded `archived` for it in the disposition record
        # A judged move therefore cannot happen without a reviewable row explaining it.
        if any(r.match(h) for r in rotate_res):
            cand.append({**s, "why": "pattern"})
        elif disp.get(section_key(h), ("", ""))[0] == "archived":
            cand.append({**s, "why": "disposition"})

    if not cand:
        notes.append(
            f"candidate set was EMPTY — {len(sections(text))} section(s) examined against "
            f"{len(rotate_res)} rotate pattern(s), none matched. Nothing to rotate is a valid "
            "no-op (this is the idempotent case), NOT evidence the file is bounded — check "
            "`just state-check` for that.")
        # Still refresh the index: an archive added by hand, or left behind by a run that failed
        # mid-write, must become REACHABLE. Deterministic, so this stays a true no-op when the
        # index already matches the directory — which is what keeps AC1's idempotency contract.
        early_dir = STATE_MD.parent / cfg["archive_dir"]
        if apply and early_dir.exists():
            refreshed = write_archive_index(text, early_dir, cfg["archive_dir"])
            if refreshed != text:
                STATE_MD.write_text(refreshed)
                notes.append("archive index refreshed (no sections moved)")
        return 0, [], notes

    # Resolved relative to the STATE.md BEING PROCESSED, not to WEB_ROOT. That is what makes a
    # fixture run self-contained: the first version anchored this at WEB_ROOT, so a probe driven
    # through W0M_STATE_MD left 19 real archive files in the repo while correctly leaving the real
    # STATE.md alone. A probe that writes into the tree it is protecting is not a probe.
    arch_dir = STATE_MD.parent / cfg["archive_dir"]
    written: list[str] = []
    drop: set[int] = set()
    for s in cand:
        chunk = "\n".join(lines[s["start"]:s["end"]])
        opens = len([l for l in lines[s["start"]:s["end"]] if _DETAILS_OPEN.match(l)])
        closes = len([l for l in lines[s["start"]:s["end"]] if _DETAILS_CLOSE.match(l)])
        if opens != closes:
            raise RetentionConfigError(
                f"refusing to move `{s['heading'][:60]}…`: its range has {opens} <details> and "
                f"{closes} </details> — removing it would leave orphaned markup. Fix the range "
                "logic in sections(), do not 'fix' the file.")
        name = cfg["archive_pattern"].format(date=_date_of(s["heading"]), slug=_slug(s["heading"]))
        path = arch_dir / name
        n = 2
        while path.exists() or str(path.relative_to(STATE_MD.parent)) in written:
            path = arch_dir / name.replace(".md", f"-{n}.md")
            n += 1
        if apply:
            arch_dir.mkdir(parents=True, exist_ok=True)
            path.write_text(
                f"<!-- Rotated out of STATE.md by `just state-rotate` (T174). Content is VERBATIM. -->\n"
                f"<!-- Archived section: {s['heading'][:120]} -->\n\n"
                + chunk.rstrip() + "\n")
        written.append(str(path.relative_to(STATE_MD.parent)))
        drop.update(range(s["start"], s["end"]))

    if apply:
        kept = [l for i, l in enumerate(lines) if i not in drop]
        new = re.sub(r"\n{4,}", "\n\n\n", "\n".join(kept))
        new = write_archive_index(new, arch_dir, cfg["archive_dir"])
        o, c = len(re.findall(r"^\s*<details[ >]", new, re.M)), len(re.findall(r"^\s*</details>\s*$", new, re.M))
        if o != c:
            raise RetentionConfigError(
                f"post-rotation STATE.md has unbalanced <details> ({o} open / {c} close) — "
                "refusing to write corrupted markdown")
        STATE_MD.write_text(new)
        notes.append(f"{len(cand)} section(s) moved · {sum(s['bytes'] for s in cand):,} B out of "
                     f"STATE.md · {len(text):,} B → {len(new):,} B")
    return len(cand), written, notes


ARCH_BEGIN = "<!-- W0M-STATE-ARCHIVE:BEGIN — generated by `just state-rotate` · do not hand-edit -->"
ARCH_END = "<!-- W0M-STATE-ARCHIVE:END -->"


def archive_index(arch_dir: Path, rel: str | None = None) -> str:
    """Render the index of rotated history — the thing that makes the archive REACHABLE.

    The point of rotation was never to hide the history, only to stop loading all of it
    unconditionally. Without an index, "moved to the archive" is indistinguishable from "deleted" to
    the next agent, who has no reason to know the directory exists.

    Regenerated wholesale from the directory listing on every run, in a deterministic order, so
    rotating twice leaves the file byte-identical (the idempotency contract in AC1).
    """
    # The link must be relative to STATE.md, which sits one level ABOVE `project/`. Using
    # `arch_dir.name` produced `state-archive/…` and every link 404'd — the index existing is not
    # the same as the index being usable, and this is exactly the kind of thing that looks right
    # in a diff and is broken for the reader.
    rel = rel or arch_dir.name
    rows = []
    for p in sorted(arch_dir.glob("*.md"), reverse=True):
        if p.name == "DISPOSITION.md":
            continue
        head = ""
        for line in p.read_text().split("\n")[:4]:
            m = re.match(r"<!-- Archived section: (.+?) -->", line.strip())
            if m:
                head = m.group(1)
                break
        head = re.sub(r"^#{2,3} ", "", head)
        head = re.sub(r"^(⭐ \(was\) PICK UP HERE|0y\d*\. superseded pickup block)\s*—?\s*", "", head)
        head = head.replace("|", "\\|").strip()
        rows.append(f"| `{p.name[:10]}` | [{p.name}]({rel}/{p.name}) | {head[:150]} |")
    if not rows:
        return (f"{ARCH_BEGIN}\n\n_No rotated history yet._\n\n{ARCH_END}")
    return (
        f"{ARCH_BEGIN}\n\n"
        "## Archived history — generated, never hand-edited\n\n"
        f"> **{len(rows)} superseded record(s)** rotated out of this file by `just state-rotate` "
        "(T174). Content is **verbatim** — nothing was summarised or deleted, and git holds the full\n"
        "> history regardless. Read one when you need to know *why* a past decision was taken; do\n"
        "> **not** read them to find out what to do next, which is what the ⭐ block above is for.\n"
        "> ⚠️ An entry here is **dated history by definition** — it was current once and is not now.\n\n"
        "| Date | Archive | What it recorded |\n|---|---|---|\n"
        + "\n".join(rows) + f"\n\n{ARCH_END}"
    )


def write_archive_index(text: str, arch_dir: Path, rel: str | None = None) -> str:
    block = archive_index(arch_dir, rel)
    if ARCH_BEGIN in text and ARCH_END in text:
        return text[: text.index(ARCH_BEGIN)] + block + text[text.index(ARCH_END) + len(ARCH_END):]
    return text.rstrip("\n") + "\n\n---\n\n" + block + "\n"


def disposition_problems(text: str) -> list[str]:
    """AC2 — every editorial section must be ACCOUNTED FOR, and an unaccounted one FAILS.

    🔴 The failure this exists to prevent is not a slow triage. It is a section that vanishes with
    nobody able to tell — and STATE.md is the only record of several expensive findings, including
    credential-incident notes and the "force-push resurrects leaked objects" warning. So the default
    is deliberately NOT archive-if-unsure: an unlisted section is an error the author must resolve.
    """
    cfg = retention_cfg()
    rec_path = STATE_MD.parent / cfg["disposition_record"]
    disp = read_disposition(rec_path)
    if not disp:
        return [f"no disposition record at {cfg['disposition_record']} — refusing to certify that "
                "STATE.md's history was triaged, because nothing recorded that it was (T174 AC2)"]

    never_res = [re.compile(p) for p in cfg["never_rotate"] if p.startswith("^")]
    live = [s for s in sections(text)
            if not any(r.match(s["heading"]) for r in never_res)
            and "Archived history" not in s["heading"]]
    unaccounted = [s["heading"] for s in live if section_key(s["heading"]) not in disp]
    problems = []
    if unaccounted:
        problems.append(
            f"{len(unaccounted)} STATE.md section(s) have NO disposition row — an unaccounted "
            "section must never default to 'archived': "
            + " · ".join(h[:56] for h in unaccounted[:4])
            + (f" · (+{len(unaccounted) - 4} more)" if len(unaccounted) > 4 else ""))
    arch_dir = STATE_MD.parent / cfg["archive_dir"]
    if arch_dir.exists():
        on_disk = {p.name for p in arch_dir.glob("*.md")} - {"DISPOSITION.md"}
        want = sum(1 for k, (d, _) in disp.items() if d == "archived")
        if len(on_disk) < want:
            problems.append(
                f"disposition records {want} archived section(s) but only {len(on_disk)} archive "
                "file(s) exist — the record and the directory disagree, so one of them is lying")
    return problems


def budget_problems(text: str) -> list[str]:
    """T174 AC4 — size budget, plus the guard that a small file is not automatically a good one.

    🔴 The load-bearing subtlety: a retention gate's natural FAILURE mode (a tiny file) is
    indistinguishable from its SUCCESS condition (a bounded file). So "under budget" is not
    sufficient — an absent, empty or content-free STATE.md must FAIL rather than be certified.
    """
    cfg = retention_cfg()
    problems: list[str] = []
    body = text
    if BEGIN in text and END in text:
        body = text[: text.index(BEGIN)] + text[text.index(END) + len(END):]
    if len(body.strip().lstrip("#").strip()) < 200:
        problems.append(
            "STATE.md has (almost) no content outside the managed block — refusing to certify it as "
            "'within budget', because an empty handoff surface satisfies every budget trivially")
    n_lines, n_bytes = text.count("\n") + 1, len(text.encode())
    if n_lines > cfg["max_lines"]:
        problems.append(
            f"STATE.md is {n_lines:,} lines, over the declared budget of {cfg['max_lines']:,} "
            f"(+{n_lines - cfg['max_lines']:,}) — run `just state-rotate`")
    if n_bytes > cfg["max_bytes"]:
        problems.append(
            f"STATE.md is {n_bytes:,} bytes, over the declared budget of {cfg['max_bytes']:,} "
            f"(+{n_bytes - cfg['max_bytes']:,}) — run `just state-rotate`")
    return problems


def budget_headroom(text: str) -> str | None:
    """T174 AC7/§6.1 — say how much room is LEFT, on the green path.

    `budget_problems` only speaks when the budget is already blown, which makes the budget
    invisible right up to the moment it blocks a push. But the agent who needs the number is the
    one about to WRITE the next ⭐ block, and by then the cost of finding out the hard way is a
    rejected push and a rotation mid-commit. So state-check reports usage every time it passes.
    Reported as a percentage of the tighter of the two limits — the one that will actually bite.
    """
    try:
        cfg = retention_cfg()
    except RetentionConfigError:
        return None   # the failure path already names it; never report a number over a bad policy
    n_lines, n_bytes = text.count("\n") + 1, len(text.encode())
    pct_l = n_lines / cfg["max_lines"] * 100
    pct_b = n_bytes / cfg["max_bytes"] * 100
    worst = max(pct_l, pct_b)
    mark = "⚠️ " if worst >= 80 else ""
    tail = " — run `just state-rotate` before adding more" if worst >= 80 else ""
    return (f"  ℹ  {mark}STATE.md {n_lines:,}/{cfg['max_lines']:,} lines ({pct_l:.0f}%) · "
            f"{n_bytes:,}/{cfg['max_bytes']:,} bytes ({pct_b:.0f}%){tail}")


def second_surface_problems() -> list[str]:
    """AC5 — the OTHER surface, and the reason the naive fix is wrong.

    MEMORY.md is auto-loaded EVERY session; STATE.md is read once, and only when an agent chooses
    to. Draining one into the other converts a large occasional cost into a permanent one, so the
    always-on surface gets a budget of its own. Absent is NOT a failure here — the memory store is
    per-machine (D36) and a fresh clone legitimately has none; only an oversized one is.
    """
    ss = (retention_cfg().get("second_surface") or {})
    f, cap = ss.get("file"), ss.get("max_bytes")
    if not f or not cap:
        return []
    p = Path(os.path.expanduser(f))
    if not p.exists():
        return []
    n = len(p.read_bytes())
    if n > cap:
        return [f"auto-memory index {p.name} is {n:,} bytes, over its declared budget of {cap:,} "
                f"(+{n - cap:,}) — consolidate memories; it loads on EVERY session, so this cost is "
                "paid unconditionally (T174 AC5)"]
    return []


