def render(data: dict) -> str:
    rows = ["| Repo | branch | dirty | unpushed | HEAD |", "|---|---|---|---|---|"]
    for rel, f in data["repos"].items():
        unpushed = "**n/a — NO UPSTREAM**" if f["unpushed"] is None or not f["has_upstream"] else str(f["unpushed"])
        if not f["has_upstream"]:
            unpushed = f"**{f['unpushed'] if f['unpushed'] is not None else '?'} (NO UPSTREAM — `@{{u}}` lies here)**"
        dirty = f"**{f['dirty']}**" if f["dirty"] else "0"
        rows.append(f"| `{rel}` | `{f['branch']}` | {dirty} | {unpushed} | `{f['head']}` |")

    gates = data["gates"]
    gate_line = " · ".join(
        f"`{k}`={'✅ 0' if v == 0 else f'🔴 {v}'}" for k, v in gates.items() if not k.startswith("_"))

    t = data["tickets"]
    rowless = ", ".join(t.get("rowless_open", [])) or "none"

    sys.path.insert(0, str(MONO_ROOT / "scripts"))
    import tasks_query  # noqa: PLC0415
    hot_md = tasks_query.markdown_hot(data.get("_hot_detail", []))
    # T151/T146: the complement to `hot`. `hot` ranks what can be STARTED and is structurally blind
