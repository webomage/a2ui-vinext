#!/usr/bin/env python3
"""STATE.md self-maintenance (T145) — render / check / write the managed block.

WHY THIS EXISTS
    `STATE.md` is the designated "read me first" handoff surface and was maintained purely by
    convention: it appeared in no hook, no `.pre-commit-config.yaml` entry, no justfile recipe and
    no `.w0m/sdlc.json` stage. Nothing could notice it was wrong, and on 2026-07-26 it went stale
    TWICE inside a single session — its repo table claimed 1 unpushed commit when there were 2, then
    0, and its "next action" pointed at a section that was already finished.

THE SPLIT THAT MAKES THIS TRACTABLE
    Most of STATE.md is EDITORIAL JUDGEMENT — the hot-10 ranking, "the lessons worth carrying",
    which owner action matters most. A hook cannot author that and must not try. But the parts that
    actually went stale are PURELY MECHANICAL: the per-repo dirty/unpushed/HEAD table, gate exit
    codes, ticket counts. Those should never be hand-written.

    So: a marker-delimited MANAGED BLOCK holds only mechanical facts and is generated. Everything
    outside the markers is prose this tool never touches.

MODE CONTRACT (AC1)
    --render   print the managed block to stdout; write nothing
    --check    compare the recorded block against reality; exit 1 on MATERIAL drift
    --write    regenerate the block in place (what `just state-save` calls)
    --brief    print the current ⭐ PICK UP HERE block (what the SessionStart hook calls)

WHY `--check` DOES NOT REWRITE (owner decision, 2026-07-26)
    Verify-only. A hook that mutates a tracked file mid-commit has to re-stage it and can fight the
    commit. The gate therefore fails with the diff and the command to fix it, and the SKILLS do the
    writing.

WHY THE STALENESS RULE IGNORES TRANSIENT FACTS (AC5 — the load-bearing subtlety)
    Comparing the recorded HEAD to the current HEAD would fail on EVERY push, because committing
    changes HEAD by definition. A gate that always fires is one people learn to bypass — and
    `--no-verify` is prohibited in this estate, so "always red" is not a survivable design. Drift is
    therefore judged on facts that only move when the handoff genuinely goes out of date.

    ⚠️ I got this wrong once inside this file. The first version excluded HEAD for that reason and
    then made the DIRTY-REPO SET blocking — which is transient in exactly the same way: `state-save`
    records "wom7web is dirty", you commit, the set changes, and save → commit → push can never
    pass. Dirtiness and unpushed counts are now RENDERED but never COMPARED.

    BLOCKING (material — only moves when the handoff is genuinely wrong):
        gate exit codes · rowless-OPEN ticket set · repo set · top-10 hot ORDER ·
        wom7web ancestry + >10 commit distance
    RENDERED ONLY (transient):
        dirty counts · unpushed counts · per-repo HEADs · hot-list scores
"""

