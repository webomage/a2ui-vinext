# Matches a TASKS.md ticket row and captures the T-id. Tolerates the id being bare (`| T12 |`),
# emphasised (`| **T12** |`) or a markdown link (`| [T12](project/tickets/T12.md) · [#9](…) |`) —
# the board uses the link form for all 155 rows. Anchored at the row start so the id must be the
# first thing in the first cell; prose mentioning a T-id further along the row cannot match.
# ⚠️ Keep in lockstep with scripts/sdlc_doctor.py::check_ticket_parity and
#    scripts/backfill_tickets.py — three parsers, one board.
TASKS_ROW_RE = r"^\|\s*[*_`]*\s*\[?\s*(T\d+[a-z]?)\s*\]?"

BEGIN = "<!-- W0M-STATE:BEGIN — generated by project/scripts/state_doctor.py · do not hand-edit -->"
END = "<!-- W0M-STATE:END -->"
# The canonical facts travel as JSON inside an HTML comment so `--check` compares data, not a
# rendered markdown table. The table above it is generated from the SAME dict, so the two can never
# disagree — a second hand-maintained copy of these numbers is the thing this tool exists to remove.
DATA_PREFIX = "<!-- W0M-STATE-DATA "
DATA_SUFFIX = " -->"

MAX_COMMIT_DRIFT = 10


def sh(args: list[str], cwd: Path) -> tuple[int, str]:
    r = subprocess.run(args, cwd=cwd, capture_output=True, text=True)
    return r.returncode, r.stdout.strip()


def declared_repos() -> list[str]:
    """Repo set comes from hygiene-policy.json — the same list the hygiene gates use.

    Deliberately NOT a hardcoded list here. A second copy would drift, and this estate has already
    had a wrong repo count three separate times.
    """
    policy = json.loads(POLICY.read_text())
    return [r["path"] for r in policy.get("repos", [])]


def repo_facts(rel: str) -> dict | None:
    repo = MONO_ROOT / rel
    if not (repo / ".git").exists():
        return None
    _, branch = sh(["git", "rev-parse", "--abbrev-ref", "HEAD"], repo)
    _, head = sh(["git", "rev-parse", "--short", "HEAD"], repo)
    _, porcelain = sh(["git", "status", "--porcelain"], repo)
    dirty = len([l for l in porcelain.splitlines() if l.strip()])
    # `git log @{u}..` returns 0 SPURIOUSLY when no upstream is configured — it errors instead of
    # reporting, which is how wom7mlx read as "0 unpushed" while holding 3. Always name the remote
    # ref explicitly, and record when there is no upstream so the number can be read honestly.
    rc_up, _ = sh(["git", "rev-parse", "--abbrev-ref", "@{u}"], repo)
    rc, out = sh(["git", "log", "--oneline", f"origin/{branch}..HEAD"], repo)
    unpushed = len([l for l in out.splitlines() if l.strip()]) if rc == 0 else None
    return {
        "branch": branch,
        "head": head,
        "dirty": dirty,
        "unpushed": unpushed,
        "has_upstream": rc_up == 0,
    }


def gate_codes() -> dict:
    """Exit codes for the hygiene gates, from ONE process (the suite costs ~5.5s)."""
    r = subprocess.run(
        [sys.executable, str(MONO_ROOT / "scripts" / "repo_hygiene.py"), "all", "--json"],
        cwd=MONO_ROOT, capture_output=True, text=True)
    try:
        report = json.loads(r.stdout)
    except Exception:  # noqa: BLE001
        return {"_error": "repo_hygiene did not return parseable JSON"}
    return {name: (1 if report[name]["problems"] else 0) for name in sorted(report)}


def ticket_facts() -> dict:
    """Open-ticket count and the ROWLESS OPEN set.

    The row regex must stay identical to `check_ticket_parity` in
    scripts/sdlc_doctor.py and to `backfill_tickets.py`. Two gates reading the same file with
    two different parsers would eventually disagree, and then neither could be trusted.

    🔴 FIXED 2026-08-05 — all three had silently gone blind. The board format changed from a bare
    `| T123 |` to a markdown link `| [T123](project/tickets/T123.md) · [#12](…) |`, and the old
    patterns anchored on a bare id. Measured against the live TASKS.md: the old state_doctor pattern
    matched **0 of 155 rows**, and sdlc_doctor's (which had already drifted to allow `**T123**`)
    also matched **0**. Consequence: `rows` reported 0, `rowless_open` contained EVERY open ticket,
    and STATE.md published "121 open · 0 TASKS.md rows · 121 OPEN ticket(s) with no row" as fact.
    The gate still tripped on set CHANGES, so it looked alive while being unable to detect the one
    thing it exists for — a genuinely rowless ticket was indistinguishable from the 121 false ones.
    `state-doctor-test` passed throughout because it asserts the *comparison* fails on drift, never
    that this fact is collected correctly.
    """
    tasks_md = MONO_ROOT / "TASKS.md"
    tickets_dir = MONO_ROOT / ".tasks"
    if not tasks_md.exists() or not tickets_dir.is_dir():
        return {"_error": "TASKS.md or .tasks/ not found"}
    rows = set(re.findall(TASKS_ROW_RE, tasks_md.read_text(), re.M))
    open_ids, rowless, unmirrored = [], [], []
    total_all = 0
    specced_all = 0
    specced_open = 0
    for path in sorted(tickets_dir.glob("T*.md")):
        total_all += 1
        head = path.read_text()[:900]
        m_sp = re.search(r"^spec:\s*(.*)$", head, re.M)
        sp_raw = re.split(r"\s+#", m_sp.group(1).strip(), maxsplit=1)[0].strip().strip('"\'') if m_sp else ""
        has_spec = bool(sp_raw)
        if has_spec:
            specced_all += 1
        m = re.search(r"^status:\s*(\S+)", head, re.M)
        status = m.group(1).strip().strip('"') if m else ""
        if status in ("done", "archived"):
            continue
        if has_spec:
            specced_open += 1
        open_ids.append(path.stem)
        if path.stem not in rows:
            rowless.append(path.stem)
        m_gh = re.search(r"^gh_issue:\s*(\S*)", head, re.M)
        gh = m_gh.group(1).strip().strip('"\'') if m_gh else ""
        if not (gh.isdigit() and gh != "0"):
            unmirrored.append(path.stem)
    key = lambda t: int(re.sub(r"\D", "", t))  # noqa: E731
    return {
        "open": len(open_ids),
        "total": total_all,
        "specced": specced_all,
        "specced_open": specced_open,
        "rows": len(rows),
        "rowless_open": sorted(rowless, key=key),
        "unmirrored_open": len(unmirrored),
    }


def pending_mirror() -> tuple[int, int] | None:
    """(pending, total) tickets whose projection differs from the sync index — T150 AC6.

    Deliberately a REPORT, not a gate, and deliberately NOT stored in the managed block:
      * blocking a push on an unsynced mirror would put a forge dependency back into the hook path
        by the back door, which is exactly what the hooks-are-legacy-git decision forbids;
      * storing it would make `--check` compare it, and a compared field IS a gate — the value would
        drift the moment anyone edited a ticket, and `state-save` would start demanding a sync.

    It is computed fresh on every run and printed, so "nobody has synced in three days" is a visible
    number rather than something discovered later on the board. Reads local files only — no network.
    """
    cache_path = os.environ.get("W0M_STATE_FACTS_CACHE")
    if cache_path:
        mp = Path(f"{cache_path}.mirror.json")
        if mp.is_file():
            try:
                cached = json.loads(mp.read_text(encoding="utf-8"))
                return (cached[0], cached[1]) if cached is not None else None
            except Exception:  # noqa: BLE001
                pass
    idx_path = WEB_ROOT / "project" / "tickets-sync-index.json"
    if not idx_path.exists():
        return None
    sys.path.insert(0, str(MONO_ROOT / "scripts"))
    try:
        import sync_github as sg  # noqa: PLC0415 — late import keeps this script standalone
        # load_tickets() rewrites project/tickets.json as a derived snapshot. `state-check` is a
        # read-only gate, so force the module's dry flag first — otherwise merely CHECKING state
        # would dirty the tree and the pre-push hook would fight the commit that ran it.
        sg.DRY = True
        recorded = sg.load_index()
        tickets = sg.load_tickets()
    except Exception:                                   # noqa: BLE001
        return None                                     # never let a report break the gate
    pending = sum(
        1 for t in tickets
        if recorded.get(t["id"]) != sg.projection_hash(sg.projection_of(t, sg.summary_of(t["id"])))
    )
    res = (pending, len(tickets))
    if cache_path:
        try:
            Path(f"{cache_path}.mirror.json").write_text(json.dumps(list(res)), encoding="utf-8")
        except Exception:  # noqa: BLE001
            pass
    return res


def hot_list(n: int = 10) -> list[dict]:
    """The top-N hot ranking, computed by tasks_query — never hand-written.

    Lives in the managed block ON PURPOSE (owner decision 2026-07-26: *"store top 10 hot as header
    for STATE.md"*, *"regenerate permanently as we close something with sdlc or update if progress to
    next step"*). Because `--check` compares the ranked ID list, **closing or advancing a ticket makes
    STATE.md stale and the pre-push gate says so** — which is the mechanism that keeps the header
    honest instead of relying on someone remembering.
    """
    sys.path.insert(0, str(MONO_ROOT / "scripts"))
    import tasks_query  # noqa: PLC0415 — deliberately late; keeps this script runnable standalone
    return tasks_query.rank(tasks_query.load(), n)


def measure() -> dict:
    import pickle  # noqa: PLC0415
    cache_path = os.environ.get("W0M_STATE_FACTS_CACHE")
    if cache_path:
        cp = Path(cache_path)
        if cp.is_file():
            try:
                return pickle.loads(cp.read_bytes())  # noqa: S301
            except Exception:  # noqa: BLE001
                pass
    repos = {}
    for rel in declared_repos():
        facts = repo_facts(rel)
        if facts is not None:
            repos[rel] = facts
    hot = hot_list()
    out = {
        "repos": repos,
        "gates": gate_codes(),
        "tickets": ticket_facts(),
        # Only the ORDERED IDS are compared. Scores drift with age by design and would make the gate
        # fire on the passage of time rather than on real movement in the queue.
        "hot": [t["id"] for t in hot],
        "_hot_detail": hot,
    }
    if cache_path:
        try:
            Path(cache_path).write_bytes(pickle.dumps(out))
        except Exception:  # noqa: BLE001
            pass
    return out


