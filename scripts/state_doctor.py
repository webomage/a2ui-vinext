def recorded(text: str) -> dict | None:
    m = re.search(re.escape(DATA_PREFIX) + r"(\{.*?\})" + re.escape(DATA_SUFFIX), text, re.S)
    if not m:
        return None
    try:
        return json.loads(m.group(1))
    except Exception:  # noqa: BLE001
        return None


def ancestry_drift(rec_head: str) -> str | None:
    """None = fine. Otherwise the reason wom7web's recorded head is materially wrong.

    Two distinct failures, and they are not the same thing:
      * NOT AN ANCESTOR — the recorded commit is not in current history at all, so the file
        describes a diverged or rewritten branch. That is always material.
      * TOO FAR BEHIND   — still an ancestor, but the narrative is >N commits stale.
    """
    rc, _ = sh(["git", "merge-base", "--is-ancestor", rec_head, "HEAD"], WEB_ROOT)
    if rc != 0:
        return (f"recorded wom7web head `{rec_head}` is NOT an ancestor of HEAD — STATE.md describes "
                "a diverged or rewritten branch")
    rc, out = sh(["git", "rev-list", "--count", f"{rec_head}..HEAD"], WEB_ROOT)
    if rc == 0 and out.isdigit() and int(out) > MAX_COMMIT_DRIFT:
        return (f"STATE.md's mechanical block is {out} commits behind HEAD "
                f"(limit {MAX_COMMIT_DRIFT})")
    return None


def check() -> tuple[list[str], dict]:
    if not STATE_MD.exists():
        return ([f"{STATE_MD.name} does not exist — the handoff surface is missing entirely"], {})
    text = STATE_MD.read_text()
    if BEGIN not in text or END not in text:
        return ([
            "STATE.md has NO managed block — refusing to certify a file this tool cannot verify. "
            f"Add one with `just state-save` (markers: {BEGIN[:32]}… / {END})"
        ], {})
    rec = recorded(text)
    if not rec:
        return (["STATE.md's managed block has no parseable W0M-STATE-DATA payload — "
                 "refusing to pass on a block whose recorded facts cannot be read"], {})

    live = measure()
    problems: list[str] = []

    # T174 AC4/AC5 — the size budget. Checked BEFORE the drift comparisons because an over-budget
    # file is wrong regardless of whether its numbers happen to be current: a handoff surface that
    # costs ~83k tokens to read has failed at its job even when every fact in it is true.
    # A malformed/absent policy is itself a failure — never a silent fallback to a built-in default.
    try:
        problems.extend(budget_problems(text))
        problems.extend(second_surface_problems())
        problems.extend(disposition_problems(text))
    except RetentionConfigError as e:
        problems.append(f"retention policy unusable: {e}")

    # Empty-set discipline (AC9): every collection compared must be non-empty, or the comparison
    # below is vacuously satisfied. This is the exact failure mode T135 §4 shipped and §6 repeated.
    if not live["repos"]:
        problems.append("measured 0 repos — refusing to compare STATE.md against an empty input set")
    if not [k for k in live["gates"] if not k.startswith("_")]:
        problems.append("measured 0 hygiene gates — refusing to compare against an empty gate set")
    if "_error" in live["tickets"]:
        problems.append(f"ticket facts unavailable: {live['tickets']['_error']}")
    if problems:
        return problems, live

    # 1. gate exit codes — the facts most likely to be silently wrong in prose
    for name, code in live["gates"].items():
        if name.startswith("_"):
            continue
        was = rec.get("gates", {}).get(name)
        if was != code:
            problems.append(
                f"gate `{name}`: STATE.md records exit {was}, reality is exit {code}")

    # 2. rowless OPEN tickets — a set, not a count: swapping one for another matters
    was_rowless = set(rec.get("tickets", {}).get("rowless_open", []))
    now_rowless = set(live["tickets"].get("rowless_open", []))
    if was_rowless != now_rowless:
        added = ", ".join(sorted(now_rowless - was_rowless)) or "—"
        gone = ", ".join(sorted(was_rowless - now_rowless)) or "—"
        problems.append(
            f"rowless OPEN tickets changed (newly invisible: {added} · now on the board: {gone})")

    # 3. The dirty-repo set is INFORMATIONAL, never blocking.
    #
    # 🔴 This was blocking in the first version and it was wrong for the same reason raw HEAD
    # comparison is wrong: dirtiness is TRANSIENT. `state-save` records "wom7web is dirty", you then
    # commit, and the set changes — so the save → commit → push sequence could never pass. The rule
    # written to avoid an always-red gate reintroduced one via a different transient fact.
    # Blocking facts must be ones that change only when the HANDOFF genuinely goes out of date.

    # 4. repo set itself
    if set(rec.get("repos", {})) != set(live["repos"]):
        problems.append(
            f"repo set changed: recorded {sorted(rec.get('repos', {}))}, "
            f"reality {sorted(live['repos'])}")

    # 5. the hot-10 ranking — THIS is what makes SDLC progress refresh the header (owner decision
    #    2026-07-26). Closing a ticket or advancing it to the next stage reorders this list, so the
    #    gate notices and STATE.md's header cannot silently describe last week's priorities.
    was_hot = rec.get("hot", [])
    now_hot = live.get("hot", [])
    if was_hot != now_hot:
        entered = [t for t in now_hot if t not in was_hot]
        left = [t for t in was_hot if t not in now_hot]
        detail = []
        if entered:
            detail.append(f"entered: {', '.join(entered)}")
        if left:
            detail.append(f"dropped: {', '.join(left)}")
        if not detail:
            detail.append(f"reordered: {' > '.join(was_hot)} → {' > '.join(now_hot)}")
        problems.append("top-10 hot list is out of date (" + " · ".join(detail) + ")")

    # 6. ancestry / distance for the repo that OWNS this file
    rec_head = rec.get("repos", {}).get("wom7web", {}).get("head")
    if rec_head:
        drift = ancestry_drift(rec_head)
        if drift:
            problems.append(drift)

    return problems, live


def generate_pickup_block(tickets_dir: Path) -> str:
    """Synthesize the ⭐ PICK UP HERE block from active ticket status notes (T428 AC2).

    Contract:
    - Heading matches PICKUP_RE and carries today's date.
    - Lists every in-progress ticket with its ID, title, and newest dated status note.
    - An in-progress ticket with no notes is explicitly flagged.
    - Lists tickets completed today to show what finished this cycle.
    """
    from datetime import date
    today = date.today().isoformat()
    items = []
    recently_done = []

    if tickets_dir.is_dir():
        for path in sorted(tickets_dir.glob("T*.md"), key=lambda p: int(re.sub(r"\D", "", p.stem) or 0)):
            text = path.read_text(encoding="utf-8", errors="replace")
            m_st = re.search(r"^status:\s*(\S+)", text[:600], re.M)
            st = m_st.group(1).strip().strip('"\'') if m_st else ""
            m_ti = re.search(r"^title:\s*[\"']?(.*?)[\"']?$", text[:600], re.M)
            title = m_ti.group(1).strip() if m_ti else path.stem
            notes = text.split("\n## Status notes", 1)[1] if "\n## Status notes" in text else ""
            best: tuple[str, str] | None = None
            for line in notes.split("\n"):
                d = _NOTE_DATE.search(line)
                if line.strip().startswith("- ") and d and (best is None or d.group(1) >= best[0]):
                    best = (d.group(1), line.strip())
            if st == "in-progress":
                items.append({"id": path.stem, "title": title, "date": best[0] if best else None,
                              "note": best[1] if best else None})
            elif st in ("done", "closed") and best and best[0] == today:
                recently_done.append({"id": path.stem, "title": title, "date": best[0], "note": best[1]})

    lines = [
        f"## ⭐ PICK UP HERE — {today} (generated) — in-flight tickets & session handoffs",
        "",
        "> **Generated by `just state-save` from ticket Status notes (`.tasks/T*.md`).**",
        "> Each session records its handoff into its active ticket's `## Status notes`.",
        "> Operational how-to lives in §0 Orient; permanent gotchas live in §4 below.",
        "",
    ]

    if items:
        lines.append(f"#### In-flight tickets ({len(items)}):")
        lines.append("")
        for it in items:
            tid = it["id"]
            title = it["title"]
            if not it["date"]:
                lines.append(f"- **{tid}** — {title}")
                lines.append("  - ⚠️ NO status note recorded where this stopped")
            else:
                age = (date.today() - date.fromisoformat(it["date"])).days
                note_raw = str(it.get("note") or "")
                note_text = re.sub(r"[*`]", "", note_raw[2:])
                note_text = _NOTE_DATE.sub("", note_text, count=1).strip(" —-:")
                age_str = f"{age}d ago" if age > 0 else "today"
                lines.append(f"- **{tid}** — {title}")
                lines.append(f"  - **{it['date']}** ({age_str}): {note_text}")
        lines.append("")
    else:
        lines.append("No tickets currently in-progress. Pick next work via `just tasks hot` or `just tasks sdlc`.")
        lines.append("")

    if recently_done:
        lines.append(f"#### Completed today ({len(recently_done)}):")
        lines.append("")
        for it in recently_done:
            tid = it["id"]
            title = it["title"]
            note_text = re.sub(r"[*`]", "", it["note"][2:])
            note_text = _NOTE_DATE.sub("", note_text, count=1).strip(" —-:")
            lines.append(f"- **{tid}** — {title} ({note_text})")
        lines.append("")

    return "\n".join(lines).rstrip()


def write() -> None:
    data = measure()
    block = render(data)
    if STATE_MD.exists():
        text = STATE_MD.read_text()
    else:
        text = "# STATE — session handoff (start here)\n"
    if BEGIN in text and END in text:
        start = text.index(BEGIN)
        finish = text.index(END) + len(END)
        text = text[:start] + block + text[finish:]
    else:
        # First install: place the block directly after the H1 so it is the first thing seen.
        lines = text.splitlines(keepends=True)
        insert_at = 1 if lines and lines[0].startswith("# ") else 0
        text = "".join(lines[:insert_at]) + "\n" + block + "\n" + "".join(lines[insert_at:])

    # T428 AC2: generate and update the ⭐ PICK UP HERE block from ticket status notes
    tickets_dir = STATE_MD.parent / ".tasks"
    if not tickets_dir.is_dir() and (MONO_ROOT / ".tasks").is_dir():
        tickets_dir = MONO_ROOT / ".tasks"

    if tickets_dir.is_dir():
        pickup_block = generate_pickup_block(tickets_dir)
        sects = sections(text)
        current = [s for s in sects if PICKUP_RE.match(s["heading"]) and "(was)" not in s["heading"]]
        if current:
            pick = max(current, key=lambda s: _date_of(s["heading"]))
            lines = text.split("\n")
            text = ("\n".join(lines[:pick["start"]]).rstrip() + "\n\n"
                    + pickup_block + "\n\n"
                    + "\n".join(lines[pick["end"]:]).lstrip())
        else:
            if "## 0. Orient" in text:
                orient_idx = text.index("## 0. Orient")
                after_orient = text.find("\n## ", orient_idx + 1)
                if after_orient != -1:
                    text = text[:after_orient].rstrip() + "\n\n" + pickup_block + "\n\n" + text[after_orient:].lstrip()
                else:
                    text = text.rstrip() + "\n\n" + pickup_block + "\n"
            elif END in text:
                end_idx = text.index(END) + len(END)
                text = text[:end_idx].rstrip() + "\n\n" + pickup_block + "\n\n" + text[end_idx:].lstrip()
            else:
                text = text.rstrip() + "\n\n" + pickup_block + "\n"

    STATE_MD.write_text(text)


_NOTE_DATE = re.compile(r"(\d{4}-\d{2}-\d{2})")


def in_flight(tickets_dir: Path) -> list[dict]:
    """Every `in-progress` ticket with its newest dated status note (T428).

    WHY. The pickup block is written when a session ENDS, so a session cut off by quota or a crash
    leaves none. The ticket it was working on is the one place such a session can have written as
    it went, so the brief lists those tickets and when each last said anything. A ticket with NO
    note is listed as such — omitting it would read as "nothing in flight".
    """
    out = []
    for path in sorted(tickets_dir.glob("T*.md"), key=lambda p: int(re.sub(r"\D", "", p.stem) or 0)):
        text = path.read_text()
        m = re.search(r"^status:\s*(\S+)", text[:600], re.M)
        if not m or m.group(1).strip().strip('"') != "in-progress":
            continue
        notes = text.split("\n## Status notes", 1)[1] if "\n## Status notes" in text else ""
        best: tuple[str, str] | None = None
        for line in notes.split("\n"):
            d = _NOTE_DATE.search(line)
            if line.startswith("- ") and d and (best is None or d.group(1) >= best[0]):
                best = (d.group(1), line)
        out.append({"id": path.stem, "date": best[0] if best else None,
                    "note": best[1] if best else None})
    return out


def _render_in_flight(items: list[dict]) -> str:
    from datetime import date
    if not items:
        return "▶ In flight: no ticket is `in-progress`."
    lines = [f"▶ In flight — {len(items)} `in-progress` ticket(s). A session cut off mid-work leaves "
             f"its trace in its ticket, not in the pickup block:"]
    for it in items:
        if not it["date"]:
            lines.append(f"  {it['id']:6} NO status note — nothing records where this stopped")
            continue
        age = (date.today() - date.fromisoformat(it["date"])).days
        text = re.sub(r"[*`]", "", it["note"][2:])
        text = _NOTE_DATE.sub("", text, count=1).strip(" —-:")
        lines.append(f"  {it['id']:6} {it['date']} ({age}d) {text[:100]}")
    return "\n".join(lines)


def brief() -> tuple[bool, str]:
    """The session-start read: in-flight tickets, then the CURRENT ⭐ PICK UP HERE block.

    WHY ONLY THE PICKUP BLOCK. It is the one section that carries INTENT — what the last session
    believed was next. The managed block is numbers, and `w0m-state-load`'s rule is that numbers are
    re-derived, never read; preflight already re-derives the repo facts on the same hook. The rest
    of the file is dated history, and `AGENTS.md`'s routing table says not to orient from it.

    WHY IT READS AND NEVER MEASURES. `--render` takes ~12s; a SessionStart hook that costs seconds
    gets removed (T147 AC1). So this is a file read, labelled as recorded rather than current.

    Returns (ok, text). Not ok = no readable pickup block, and the text says which way it failed —
    an empty brief printed as success would tell the next session "nothing is in flight".
    """
    if not STATE_MD.exists():
        return False, f"❌ STATE brief: {STATE_MD} does not exist — no handoff to read"
    text = STATE_MD.read_text()
    lines = text.split("\n")
    current = [s for s in sections(text)
               if PICKUP_RE.match(s["heading"]) and "(was)" not in s["heading"]]
    tickets = STATE_MD.parent / ".tasks"
    flight = _render_in_flight(in_flight(tickets)) if tickets.is_dir() else (
        f"❌ In flight: {tickets} not found — cannot list in-progress tickets")
    if not current:
        return False, (f"❌ STATE brief: no current ⭐ PICK UP HERE block in {STATE_MD.name} — "
                       "the last session left no handoff; run `just state-check` before assuming "
                       f"nothing is in flight\n\n{flight}")
    # Newest by DATE, not position — the same rule rotation uses, so the brief and the rotation
    # can never disagree about which block is live.
    pick = max(current, key=lambda s: _date_of(s["heading"]))
    body = "\n".join(lines[pick["hstart"]:pick["end"]]).rstrip()
    head = (f"▶ STATE.md handoff — RECORDED, not measured. Read for intent; re-derive every "
            f"number (`just state-check`, `just tasks`). Full pickup gate: `w0m-state-load`.")
    if len(current) > 1:
        head += (f"\n [WARN] {len(current)} current pickup blocks — showing the newest; "
                 f"`just state-rotate` retires the rest")
    return True, f"{head}\n\n{flight}\n\n{body}"


def main() -> int:
    ap = argparse.ArgumentParser(description="STATE.md managed-block tool (T145)")
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--render", action="store_true", help="print the block, write nothing")
    mode.add_argument("--check", action="store_true", help="exit 1 on material drift")
    mode.add_argument("--write", action="store_true", help="regenerate the block in place")
    mode.add_argument("--rotate", action="store_true",
                      help="move superseded history to the archive (T174); idempotent")
    mode.add_argument("--brief", action="store_true",
                      help="print the current PICK UP HERE block for session start; write nothing")
    args = ap.parse_args()

    if args.brief:
        ok, out = brief()
        print(out)
        return 0 if ok else 1
    if args.render:
        print(render(measure()))
        return 0
    if args.write:
        write()
        try:
            target = STATE_MD.relative_to(MONO_ROOT)
        except ValueError:
            target = STATE_MD
        print(f"✅ STATE.md managed block refreshed — {target}")
        return 0
    if args.rotate:
        try:
            moved, files, notes = rotate()
        except RetentionConfigError as e:
            print(f"❌ state-rotate refused to run: {e}")
            return 1
        for n in notes:
            print(f" [INFO] {n}")
        for f in files:
            print(f"  →  {f}")
        # Name the scope, not just the verdict (T149 AC2): "moved 0" and "found nothing to look at"
        # are different facts, and the notes above distinguish them.
        print(f"✅ state-rotate: {moved} section(s) archived → "
              f"{retention_cfg()['archive_dir']}")
        return 0

    problems, live = check()
    _report_pending_mirror()   # always reported, on the pass AND the fail path
    if problems:
        print(f"❌ state-check failed ({len(problems)} drift(s)) — STATE.md is stale:")
        for p in problems:
            print(f"  ✗  {p}")
        print("\n  Fix: `just state-save`, then review the EDITORIAL sections (pickup block, hot list,")
        print("  owner actions) — the tool only refreshes mechanical facts, never judgement.")
        print("  Do NOT reach for --no-verify; it is prohibited in this estate.")
        return 1
    # Name the set enumerated (T149 AC2 / section 1): a verdict without its scope cannot be
    # distinguished from a verdict over nothing.
    print(f"✅ state-check passed — STATE.md's mechanical block matches reality "
          f"(enumerated {len(live.get('repos', {}))} repo(s), {live.get('tickets', {}).get('open', '?')} open "
          f"ticket(s), {len(live.get('gates', {}))} gate(s))")
    headroom = budget_headroom(STATE_MD.read_text())
    if headroom:
        print(headroom)
    return 0


def _report_pending_mirror() -> None:
    """T150 AC6(b) — a REPORT. Never changes the exit code."""
    pm = pending_mirror()
    if pm is None:
        return
    pending, total = pm
    if pending:
        print(f" [INFO] {pending} of {total} ticket(s) pending mirror — run `just sync-tickets` "
              f"(report only, never blocks a push)")
    else:
        print(f" [INFO] ticket mirror up to date ({total} tickets)")


if __name__ == "__main__":
    sys.exit(main())
