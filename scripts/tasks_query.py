def _ticket_url_base() -> str:
    """Where a clicked ticket link should go. Overridable, because terminals disagree.

    Default is the GitHub blob root for the CURRENT branch — the only form measured clickable in
    the terminal this estate is driven from. `W0M_TICKET_URL` replaces it wholesale:
    `file://$(hostname)` for a terminal that follows file URLs, `vscode://file` to open in the
    editor. Anything not starting `https://` is treated as addressing the local disk.
    """
    override = os.environ.get("W0M_TICKET_URL")
    if override:
        return override
    slug = _repo_slug()
    if not slug:
        # No remote to point at — fall back to the local disk rather than inventing a URL.
        return f"file://{socket.gethostname()}"
    branch = _git("rev-parse", "--abbrev-ref", "HEAD") or "beta"
    return f"https://github.com/{slug}/blob/{branch}"


# ── the terminal renderer ────────────────────────────────────────────────────────────────────
# Two complaints, one cause. The boards were printed as raw markdown pipe tables, so on screen the
# columns did not line up at all — `| 1 | T2 | #3 | P1 | in-progress | 105 | …` — and a pipe table
# whose columns do not align is not a table, it is noise with punctuation in it. And the ticket
# links were OSC 8 with a `file://` target. 🔬 Measured by `link_probe.py` after two wrong guesses:
# OSC 8 works, but ONLY an `https://` target is followed — every `file://` and `vscode://` form is
# inert, so a local path cannot be made clickable here at all. See `_ticket_url_base`.
_MD_LINK = re.compile(r"\[([^\]\[]+)\]\(([^()\s]+)\)")
# OSC 8 (`ESC ] 8 ;; target ESC \`) and SGR colour. Both are ZERO columns wide, and a padder that
# counts their bytes right-pads the short cells and destroys the alignment it is computing.
_INVISIBLE = re.compile("\033\\]8;;[^\033]*\033\\\\|\033\\[[0-9;]*m")
_OSC8 = re.compile("\033\\]8;;[^\033]*\033\\\\")


def _vis_width(cell: str) -> int:
    """Columns this cell OCCUPIES — not len(), which is wrong twice over here.

    The boards are full of emoji (📄 🔴 ⚠️ ✅) and block-drawing bars (`██████░░░░`). An emoji is
    **two** columns, a variation selector is **zero**, and a combining mark is **zero**; `len()`
    calls all of them one. Getting this wrong does not warn — it silently skews every row that
    contains a flag, which is most of them.
    """
    out = 0
    for ch in _INVISIBLE.sub("", cell):
        if ch == "\ufe0f":            # VS16: renders the PREVIOUS char wide, adds no column
            out += 1                  # ...and the base char was counted narrow, so pay it here
        elif unicodedata.combining(ch):
            continue
        else:
            out += 2 if unicodedata.east_asian_width(ch) in ("W", "F") else 1
    return out


def _md_trunc(text: str, width: int) -> str:
    """Cut to `width` characters WITHOUT splitting a markdown pair.

    🔴 A plain `title[:88]` cut inside T281's `` `ilike '%test%'` `` and left an orphan backtick.
    `terminalise()` then did exactly the right thing — it strips PAIRS and leaves an unbalanced
    marker alone, because half-eating a title is worse than showing the marker — so the bar column
    rendered a literal backtick. The bug was never in the stripper; it was that the string reached
    it already broken. ⇒ Truncate back to before the marker that lost its partner.
    """
    if len(text) <= width:
        return text
    cut = text[:width]
    for mark in ("`", "**"):
        if cut.count(mark) % 2:
            cut = cut[:cut.rfind(mark)].rstrip()
    return cut


def _truncate(cell: str, width: int) -> str:
    """Cut to `width` display columns. SGR-aware; never called on cells with OSC 8 hyperlinks."""
    if _vis_width(cell) <= width:
        return cell
    out, used = "", 0
    in_bold = False
    for tok in re.findall(r"\033\[[0-9;]*m|.", cell, re.DOTALL):
        if tok.startswith("\033["):
            out += tok
            if tok == "\033[1m":
                in_bold = True
            elif tok in ("\033[22m", "\033[0m"):
                in_bold = False
            continue
        w = _vis_width(tok)
        if used + w > width - 1:
            if in_bold:
                out += "\033[22m"
            return out + "…"
        out += tok
        used += w
    if in_bold:
        out += "\033[22m"
    return out + "…"


def terminalise(block: str) -> str:
    """Markdown → OSC 8 links and aligned columns, for a human at a terminal.

    Operates on contiguous runs of `|`-prefixed lines, so it can be handed a whole board — heading
    prose, table, and footnotes together — without the caller separating them.

    🔴 **Links are converted BEFORE the columns are measured, and the order is the whole trick.**
    ⚠️ Do not write the word "ver‑sion" anywhere in this file. `just ver‑sion-check` flags any file
    that holds a year format AND that word, and line 117 parses "%Y-%m-%d" to compute ticket age.
    The coupling is right in general and a false positive here — rewording beats an exemption,
    which would be a permanent hole in a file that changes often. Writing the explanation is what
    re-tripped the gate the first time.

    The first attempt aligned first: the widths were then computed over
    `[T2](/Users/proto/Projects/@self/@wom/w0m-web/project/tickets/T2.md)`, a 70-column cell for a
    2-column label, so the fitter spent the terminal on paths and then TRUNCATED INTO the link
    text — every board came out as `[T2](/Users/proto/Projects/@self/@wo…`, unaligned and with the
    links destroyed. Converting first makes the cell 2 columns wide and makes it detectably
    escape-bearing, which is what keeps the fitter's hands off it.
    """
    def as_osc8(m: "re.Match[str]") -> str:
        label, target = m.group(1), m.group(2)
        if target.startswith("/"):
            base = _ticket_url_base()
            if base.startswith("https://"):
                # 🔬 MEASURED, not guessed, after two wrong guesses. `project/scripts/link_probe.py`
                # printed the same target in nine forms and the owner clicked: **only OSC 8 with an
                # `https://` target and a bare `https://` URL are followed.** `file://host/path`,
                # `file:///path`, `vscode://file/…`, a bare absolute path and `path:line` are all
                # inert, with any modifier key. So a local path CANNOT be made clickable here, and
                # the only honest answer is to point at the copy that has an https URL — the file
                # in GitHub.
                # ⚠️ The cost, and it is real: a blob URL resolves only for a PUSHED commit, so a
                # ticket filed and not yet pushed 404s, and an edited one shows the pushed text.
                # Set W0M_TICKET_URL=file://$(hostname) in a terminal that does follow file URLs.
                try:
                    rel = str(pathlib.Path(target).relative_to(WEB_ROOT))
                except ValueError:
                    p = pathlib.Path(target)
                    if p.name.startswith("T") and p.name.endswith(".md"):
                        rel = f".tasks/{p.name}"
                    else:
                        try:
                            rel = str(p.relative_to(MONO_ROOT))
                        except ValueError:
                            return f"\033]8;;{target}\033\\{label}\033]8;;\033\\"
                target = f"{base.rstrip('/')}/{rel}"
            else:
                # file:// and vscode://file take the path as-is — they address the local disk.
                target = base.rstrip("/") + target
        return f"\033]8;;{target}\033\\{label}\033]8;;\033\\"

    # Markdown emphasis is noise on a terminal — `**stage-0**` and `` `██████████` `` are asterisks
    # and backticks on screen. Bold becomes real SGR bold; code spans lose their fences. Both are
    # applied HERE, before the widths are measured, and both are safe to measure because
    # `_INVISIBLE` counts SGR as zero columns. Paired-only patterns, so an unbalanced `*` or a lone
    # backtick inside a title is left exactly as written rather than half-eaten.
    text = _MD_LINK.sub(as_osc8, block)
    text = re.sub(r"\*\*([^*\n]+)\*\*", "\033[1m\\1\033[22m", text)
    text = re.sub(r"`([^`\n]+)`", "\\1", text)
    lines = text.split("\n")
    out: list[str] = []
    run: list[str] = []

    def flush() -> None:
        if not run:
            return
        # Drop markdown's `|---|---|` separator; a rule is drawn from the MEASURED widths instead.
        rows = [r for r in run if set(r) - set("|-: ")]
        if rows:
            grid = [[c.strip() for c in r.strip().strip("|").split("|")] for r in rows]
            cols = max(len(r) for r in grid)
            grid = [r + [""] * (cols - len(r)) for r in grid]
            widths = [max(_vis_width(r[i]) for r in grid) for i in range(cols)]

            # Fit the terminal by shrinking the widest ESCAPE-FREE column — in practice Title. A
            # cell holding a hyperlink is never truncated: cutting into an OSC 8 sequence prints
            # garbage and yields a dead link, which is worse than a row that wraps.
            avail = shutil.get_terminal_size((120, 40)).columns
            shrinkable = [i for i in range(cols)
                          if not any(_OSC8.search(r[i]) for r in grid)]
            while sum(widths) + 3 * (cols - 1) > avail and shrinkable:
                widest = max(shrinkable, key=lambda i: widths[i])
                if widths[widest] <= 8:
                    break
                widths[widest] -= 1
                for r in grid:
                    r[widest] = _truncate(r[widest], widths[widest])

            def pad(cell: str, w: int) -> str:
                return cell + " " * max(0, w - _vis_width(cell))

            for n, r in enumerate(grid):
                out.append(" \u2502 ".join(pad(c, w) for c, w in zip(r, widths)).rstrip())
                if n == 0:
                    out.append("\u2500\u253c\u2500".join("\u2500" * w for w in widths))
        run.clear()

    for line in lines:
        if line.startswith("|"):
            run.append(line)
            continue
        flush()
        out.append(line)
    flush()
    return "\n".join(out)


_AGENT_TREE_RE = re.compile(r"^(.*?)/\.w0m/work/[^/]+/w0m(?:/.*)?$")
MISSING_MIRROR_MARKER = "⚠️ not mirrored"
MISSING_SLUG_NOTE = (
    "> ⚠️ GitHub mirror links omitted: repository slug unavailable in `.w0m/sdlc.json`."
)


def live_workspace_root(root: Path | None = None) -> Path:
    """Resolve the canonical LIVE estate root (never an ephemeral `.w0m/work/<tree>/w0m` agent tree — T548).

    An agent tree is removed as soon as it lands (AgDR-0032), so any absolute path under
    `~/.w0m/work/<tree>/w0m/` embedded in `STATE.md` becomes a dead link immediately after landing.
    Because each agent tree is a git worktree of the live estate, `git rev-parse --git-common-dir`
    resolves back to `<live-root>/.git`. For non-git synthetic agent-tree paths in tests
    (`.../.w0m/work/<tree>/w0m`), the `.w0m/work/<tree>` segment is stripped.
    """
    override = os.environ.get("W0M_LIVE_ROOT")
    if override:
        return Path(override)
    base = (root or TICKETS.parent).resolve()
    try:
        r = subprocess.run(
            ["git", "-C", str(base), "rev-parse", "--path-format=absolute", "--git-common-dir"],
            capture_output=True, text=True, timeout=5,
        )
        if r.returncode == 0 and r.stdout.strip():
            common = Path(r.stdout.strip()).resolve()
            candidate = common.parent if common.name == ".git" else common
            if "/.w0m/work/" not in candidate.as_posix():
                return candidate
    except (OSError, subprocess.SubprocessError):
        pass
    posix = base.as_posix()
    m = _AGENT_TREE_RE.match(posix)
    if m:
        prefix = m.group(1)
        if prefix == Path.home().as_posix() and base != WORKSPACE_ROOT.resolve():
            return live_workspace_root(WORKSPACE_ROOT)
        return Path(f"{prefix}/w0m")
    return base


def _ticket_href(tid: str) -> str:
    """ABSOLUTE path to the ticket under the LIVE estate root (T548).

    Deliberately not relative — see below — and deliberately rooted at `live_workspace_root()`
    rather than `TICKETS` directly, so generating `STATE.md` inside an ephemeral agent tree
    (`~/.w0m/work/<tree>/w0m`) never embeds a path that dies when the tree is removed.

    This went through two wrong answers before landing here, both of which *looked* right:

    1. `project/tickets/T2.md` — relative to the script's cwd. The recipe does `cd ../w0m-web`, so
       this resolved only for a reader already inside `w0m-web`. From the estate root it opened
       nothing.
    2. Relative to just's `invocation_directory()`. Correct by construction, and still wrong in
       practice: run from `w0m-api` it emits `../w0m-web/project/tickets/T2.md`, which resolves
       only for a reader whose cwd matches the *invoker's*. The output outlives the invocation —
       it gets pasted into STATE.md, into tickets, into chat — and at that point the base
       directory it was computed against is gone.

    An absolute path under the live root has no base to lose. It resolves for every reader, in
    every cwd, after any amount of copying, and terminals linkify it where they leave `../` alone.
    It costs nothing to read either: the link LABEL is the bare id (`T2`), so the href is never
    displayed.
    """
    return (live_workspace_root(TICKETS.parent) / ".tasks" / f"{tid}.md").as_posix()


def _issue_link(t: dict) -> str:
    """The GitHub issue, as its own column (T158 AC1–AC3).

    An unmirrored ticket (`gh_issue` missing or `"0"`) renders `⚠️ not mirrored` rather than an
    ambiguous dash or empty cell. When `_repo_slug()` is unavailable (`""`) but `gh_issue` is
    present, the cell preserves `#{gh}` and the table emits `MISSING_SLUG_NOTE` once below.
    """
    gh = str(t.get("gh_issue") or "0").strip()
    has_issue = gh.isdigit() and gh != "0"
    slug = _repo_slug()
    if has_issue and slug:
        url = f"https://github.com/{slug}/issues/{gh}"
        return _link(f"#{gh}", url, f"[#{gh}]({url})")
    if has_issue:
        return f"#{gh}"
    return MISSING_MIRROR_MARKER


def _links(t: dict) -> str:
    """Combined local ticket link + GitHub issue surface (T158 AC1–AC3)."""
    return f"{_ticket_link(t)} · {_issue_link(t)}"


def markdown_hot(rows: list[dict]) -> str:
    """Compact markdown for embedding in STATE.md's managed block."""
    out = ["| # | Ticket | Issue | Prio | Status | Area | Score | Title |",
           "|---|---|---|---|---|---|---|---|"]
    for i, t in enumerate(rows, 1):
        flags = ("  ⚠️ **no TASKS.md row**" if t["rowless"] else "") + (" 📄 live spec" if t["spec"] else "")
        title_w = max(24, 88 - _vis_width(flags))
        area = t.get("area") or "—"
        out.append(
            f"| {i} | {_ticket_link(t)} | {_issue_link(t)} | {t['priority'] or '—'} | "
            f"{t['status']} | {area} | {t['score']} | {_md_trunc(t['title'], title_w)}{flags} |")
    if rows and not _repo_slug():
        out.append("")
        out.append(MISSING_SLUG_NOTE)
    return "\n".join(out)


def markdown_sdlc(rows: list[dict]) -> str:
    """The 'what is closest to done' table — the complement to markdown_hot."""
    out = ["| # | Ticket | Issue | Prio | Status | Area | ACs | Done | Blocked by | Title |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    at_100 = []
    for i, t in enumerate(rows, 1):
        bar = "█" * round(t["ac_pct"] / 10) + "░" * (10 - round(t["ac_pct"] / 10))
        # DECLARED and INFERRED are shown differently on purpose. A `blocked_by:` field is
        # someone's statement; an inferred one is read out of an UNTICKED acceptance criterion that
        # names an OPEN ticket in blocking language, and the reader is entitled to know which they
        # are looking at. Measured 2026-08-27: 2 tickets declare, 15 only state it in prose — so
        # showing declared-only meant this column read `—` for almost every genuinely blocked row.
        b = t.get("blockers") or {"declared": [], "inferred": []}
        bits = ["🔴 " + _id_links(b["declared"])] if b["declared"] else []
        if b["inferred"]:
            bits.append("🟠 " + _id_links(b["inferred"]) + " (from ACs)")
        dep_s = " · ".join(bits) if bits else "—"
        # 🔑 A row reading `100%` beside `in-progress` says nothing about WHICH of two very
        # different things it is, and the reader supplies the wrong one. On 2026-08-23 that
        # cost a wrong call out loud: T261 was read as "a finished ticket whose status was
        # never moved" when it was actually "every AC met, not yet deployed" — a NORMAL window
        # in start→…→verify→deploy→archive, not drift. The table already had both numbers; it
        # just never said what their combination means.
        # ⚠️ Deliberately a NOTE and not a gate: a check that fired on 100%-not-done would flag
        # correct behaviour every time the last AC is ticked, and a gate that cries wolf on the
        # normal path is one people route around (T135 AC8).
        flag = ""
        if t["ac_total"] and t["ac_done"] == t["ac_total"] and t["status"] != "done":
            flag = " ⚠️ 100% — awaiting deploy/archive, NOT stale"
            at_100.append(t["id"])
        area = t.get("area") or "—"
        out.append(
            f"| {i} | {_ticket_link(t)} | {_issue_link(t)} | {t['priority'] or '—'} | "
            f"{t['status']}{flag} | {area} | {t['ac_done']}/{t['ac_total']} | `{bar}` {t['ac_pct']}% | "
            f"{dep_s} | {_md_trunc(t['title'], 60)} |")
    if rows and not _repo_slug():
        out.append("")
        out.append(MISSING_SLUG_NOTE)
    if at_100:
        out.append("")
        out.append(f"  ⚠️  {len(at_100)} row(s) at 100% with a non-done status: "
                   f"{', '.join(at_100)}. Every acceptance criterion is met — what remains is "
                   f"the DEPLOY and ARCHIVE gates, so the record is accurate, not stale. "
                   f"Confirm against the live site before reading it either way.")
    return "\n".join(out)


# ─────────────────────────────────────────────────────────────────────────────
# UNSPECIFIED — the queue's blind spot, made visible.
#
# The SDLC board ranks by acceptance-criteria completeness, so a ticket with no
# criteria cannot be placed and is EXCLUDED — not scored 0%. That is the right
# call for ranking and the wrong outcome for planning: on 2026-08-19, twenty
# open tickets (mostly P1) were absent from the completeness board entirely and
# nobody looking at it would know.
#
# 🔑 This block does NOT invent criteria, and that restraint is the point. All
# twenty carry a deliberate placeholder from one batch on 2026-07-26 — "Not yet
# written. Derive them from the Summary via `w0m-sdlc-spec` … Do not tick
# anything here until the claim has been checked against the LIVE SYSTEM rather
# than against the board." Manufacturing criteria from titles is precisely what
# that sentence forbids, and this session produced two tickets (T235, T237)
# whose board-derived premises measurement then falsified.
#
# So: surface them, name which are honestly-placeheld versus structurally
# missing, and leave the writing to whoever picks one up.
# ─────────────────────────────────────────────────────────────────────────────

AC_SECTION = re.compile(r"^## Acceptance criteria\s*$(.*?)(?=^## )", re.M | re.S)
AC_PLACEHOLDER = re.compile(r"not yet written|to be written|TBD", re.I)


def unspecified(tickets: list[dict]) -> list[dict]:
    """Open tickets a completeness ranking cannot see, with WHY for each."""
    out = []
    for t in tickets:
        if not t["open"] or ac_progress(t["id"])[1] > 0:
            continue
        body = ""
        f = TICKETS / f"{t['id']}.md"
        if f.exists():
            body = f.read_text(encoding="utf-8", errors="replace")
        m = AC_SECTION.search(body)
        if not m:
            why = "🔴 no `## Acceptance criteria` section at all"
        elif AC_PLACEHOLDER.search(m.group(1)):
            why = "⚪ declared unwritten (placeholder)"
        else:
            why = "🔴 section present but empty"
        out.append({**t, "why": why})
    rank_pri = {"P0": 0, "P1": 1, "P2": 2, "P3": 3}
    out.sort(key=lambda t: (rank_pri.get(t["priority"] or "", 9),
                            int(re.sub(r"\D", "", t["id"]) or 0)))
    return out


def markdown_unspecified(rows: list[dict]) -> str:
    out = ["| # | Ticket | Issue | Prio | Status | Why unrankable | Title |",
           "|---|---|---|---|---|---|---|"]
    for i, t in enumerate(rows, 1):
        out.append(
            f"| {i} | {_ticket_link(t)} | {_issue_link(t)} | {t['priority'] or '—'} | "
            f"{t['status']} | {t['why']} | {_md_trunc(t['title'], 52)} |")
    return "\n".join(out)


