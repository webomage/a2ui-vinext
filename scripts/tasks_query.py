# T163. `hot` and `sdlc` both rank INDIVIDUAL tickets, so neither answers "what THEME is this
# queue actually about" — with 119 open tickets, the shape matters more than the top 10.
#
# Every grouping here reports its own coverage, because a group-by silently drops what it cannot
# key on: 39 of 119 tickets carry no `epic` at all, and rolling up without saying so would present
# 80 tickets as the whole roadmap. That is this estate's organising failure mode (a count over a
# partial set, printed as a total), so each block states its denominator.
EPIC_ROLLUP = re.compile(r"ROADMAP\s*§\s*(\d+)")


_SLUG_TO_ROADMAP: dict[str, str] | None = None


def parse_roadmap_epic_slugs(rm_path: pathlib.Path | None = None) -> dict[str, str]:
    """Return {section_id: slug} parsed directly from `> **Epic slug:**` lines in ROADMAP.md (T531 AC2)."""
    target = rm_path
    if target is None:
        target = WORKSPACE_ROOT / "ROADMAP.md" if (WORKSPACE_ROOT / "ROADMAP.md").is_file() else WEB_ROOT / "ROADMAP.md"
    if not target.is_file():
        return {}
    epics: dict[str, str] = {}
    current_sec: str | None = None
    for line in target.read_text(encoding="utf-8", errors="replace").splitlines():
        m_sec = re.match(r"^##\s+(\d+)\.", line)
        if m_sec:
            current_sec = m_sec.group(1)
            continue
        m_slug = re.match(r"^>\s*\*\*Epic slug[^*]*\*\*:?\s*[`\"]([a-z0-9-]+)[`\"]", line, re.I)
        if m_slug and current_sec and current_sec not in epics:
            epics[current_sec] = m_slug.group(1).lower()
            continue
        m_sub = re.match(
            r"^\*\s+\*\*(\d+\.\d+)\s+.*?\*\*.*?\*\*Epic slug:\*\*\s*[`\"]([a-z0-9-]+)[`\"]",
            line,
            re.I,
        )
        if m_sub:
            epics[m_sub.group(1)] = m_sub.group(2).lower()
    return epics


def _load_slug_to_roadmap(rm_path: pathlib.Path | None = None) -> dict[str, str]:
    global _SLUG_TO_ROADMAP
    if rm_path is not None:
        return {slug: f"ROADMAP §{sec}" for sec, slug in parse_roadmap_epic_slugs(rm_path).items()}
    if _SLUG_TO_ROADMAP is not None:
        return _SLUG_TO_ROADMAP
    _SLUG_TO_ROADMAP = {
        slug: f"ROADMAP §{sec}"
        for sec, slug in parse_roadmap_epic_slugs().items()
    }
    return _SLUG_TO_ROADMAP


def epic_key(epic: str, rm_path: pathlib.Path | None = None) -> str:
    """Roll `ROADMAP §13.2 — skills platform` up to `ROADMAP §13`, or map epic slug to ROADMAP section.

    Deliberate: §13, §13.2, §13.3 and `§13 — platform tooling (child of T149)` are four spellings
    of one roadmap section. Grouping on the raw string splits related work into singletons and
    makes the biggest theme in the queue look like four small ones.
    """
    m = EPIC_ROLLUP.search(epic or "")
    if m:
        return f"ROADMAP §{m.group(1)}"
    slugs = _load_slug_to_roadmap(rm_path)
    if epic and epic.lower() in slugs:
        sec = slugs[epic.lower()]
        m_slug = EPIC_ROLLUP.search(sec)
        return f"ROADMAP §{m_slug.group(1)}" if m_slug else sec
    return epic or ""



# T353. `epic:` rolls up to a ROADMAP section number, which answers "why" but has to be looked up
# to be read, and a ticket must pick exactly one. `tags` roll up on their OWN spelling instead —
# `client_alfa_kyc` names itself at every level without opening ROADMAP.md, and a ticket can sit
# under several families at once. The two axes are complementary, not a replacement: keep both.
#
# Convention: a tag namespaces itself with `_`, most-general segment first — `sdlc`,
# `sdlc_design`, `sdlc_design_gate` are the 3 depths of one family. A flat tag (no `_`) is its
# own single-level family. Not retrofitted onto existing tags (153 distinct, mostly flat, over
# 119 tickets) — this is the convention for tags written from here on.
TAG_FAMILY_DEPTH = 3


def tag_family(tag: str) -> list[str]:
    """Cumulative ancestor chain for a namespaced tag, most-general first.

    `tag_family("sdlc_design_gate") == ["sdlc", "sdlc_design", "sdlc_design_gate"]`
    `tag_family("security") == ["security"]`
    Capped at `TAG_FAMILY_DEPTH` segments — a 4th `_` is part of the leaf name, not a new level.
    """
    parts = (tag or "").split("_")
    if len(parts) > TAG_FAMILY_DEPTH:
        parts = parts[:TAG_FAMILY_DEPTH - 1] + ["_".join(parts[TAG_FAMILY_DEPTH - 1:])]
    return ["_".join(parts[:i]) for i in range(1, len(parts) + 1)]


def tag_matches(tag: str, query: str) -> bool:
    """`query` matches `tag` itself or any tag in its family under `query` (prefix on `_`)."""
    return tag == query or tag.startswith(query + "_")


def _bar(done: int, total: int, width: int = 10) -> str:
    pct = int(round(100 * done / total)) if total else 0
    return f"`{'█' * (pct * width // 100)}{'░' * (width - pct * width // 100)}` {pct:>3}%"


def resolve_current_ticket(tickets: list[dict]) -> str | None:
    """Find the current ticket from git branch, latest commit, or top in-progress ticket."""
    try:
        branch = subprocess.check_output(
            ["git", "branch", "--show-current"],
            stderr=subprocess.DEVNULL, text=True
        ).strip()
        m = re.search(r"\bT(\d+)\b", branch, re.I)
        if m:
            return f"T{m.group(1)}"
        log = subprocess.check_output(
            ["git", "log", "-n", "1", "--format=%s"],
            stderr=subprocess.DEVNULL, text=True
        ).strip()
        m = re.search(r"\bT(\d+)\b", log, re.I)
        if m:
            return f"T{m.group(1)}"
    except Exception:
        pass
    in_prog = [t for t in tickets if t.get("open") and t.get("status") == "in-progress"]
    if in_prog:
        in_prog.sort(key=lambda t: (-t.get("score", 0), num(t["id"])))
        return in_prog[0]["id"]
    return None


def build_dynamic_plan(matched_tickets: list[dict], name: str, roadmap: str = "") -> dict:
    """Build a plan structure on the fly from a set of tickets, grouped by status lifecycle."""
    if not matched_tickets:
        return {}

    in_prog = [t for t in matched_tickets if t.get("open") and t.get("status") == "in-progress"]
    queued = [t for t in matched_tickets if t.get("open") and t.get("status") == "queued"]
    blocked = [t for t in matched_tickets if t.get("open") and t.get("status") in ("blocked", "paused")]
    done = [t for t in matched_tickets if not t.get("open") or t.get("status") == "done"]

    for group in (in_prog, queued, blocked, done):
        group.sort(key=lambda t: (-t.get("score", 0), num(t["id"])))

    stages = []
    if in_prog:
        stages.append({
            "id": "wip",
            "name": "In Progress (Active Work)",
            "blocking": True,
            "tickets": [t["id"] for t in in_prog],
        })
    if queued:
        stages.append({
            "id": "queued",
            "name": "Queued (Ready)",
            "blocking": False,
            "tickets": [t["id"] for t in queued],
        })
    if blocked:
        stages.append({
            "id": "blocked",
            "name": "Blocked / Paused",
            "blocking": False,
            "tickets": [t["id"] for t in blocked],
        })
    if done:
        stages.append({
            "id": "done",
            "name": "Completed",
            "blocking": False,
            "tickets": [t["id"] for t in done],
        })

    active = "wip" if in_prog else ("queued" if queued else "done")
    return {
        "name": name,
        "roadmap": roadmap or (epic_key(matched_tickets[0].get("epic", "")) if matched_tickets else ""),
        "active_stage": active,
        "stages": stages,
    }


def load_plan(epic: str | None = None,
              tickets_filter: str | list[str] | None = None,
              tag: str | None = None,
              plan_name: str | None = None,
              tickets: list[dict] | None = None) -> dict:
    """The declared current plan from `.w0m/sdlc.json → current_plan`, or dynamic projection.

    Supports:
      1. Default: reads `.w0m/sdlc.json -> current_plan` (or `plans[active_plan]`)
      2. Named plan: reads `.w0m/sdlc.json -> plans[plan_name]`
      3. Dynamic Epic: `--epic <name|section|current>` selects all tickets under that Epic
      4. Dynamic Ticket Set: `--tickets T232,T192` builds a plan for those tickets
      5. Dynamic Tag: `--tag <name>` builds a plan for all tickets with that tag
    """
    f = WORKSPACE_ROOT / ".w0m" / "sdlc.json"
    conf = {}
    try:
        conf = json.loads(f.read_text())
    except (OSError, json.JSONDecodeError) as exc:
        print(f"❌ cannot read {f} — {exc}", file=sys.stderr)
        return {"_error": str(exc)}

    # Check for CLI or explicit dynamic overrides:
    if epic or tickets_filter or tag:
        all_t = tickets if tickets is not None else load()
        by_id = {t["id"]: t for t in all_t}

        if epic:
            if epic.lower() == "current":
                cur_id = resolve_current_ticket(all_t)
                cur_t = by_id.get(cur_id) if cur_id else None
                cur_epic = cur_t.get("epic") if cur_t else None
                if not cur_epic:
                    # Look for top in-progress ticket that declares an epic
                    for t in all_t:
                        if t.get("open") and t.get("status") == "in-progress" and t.get("epic"):
                            cur_epic = t.get("epic")
                            break
                if cur_epic:
                    epic = str(cur_epic)
                else:
                    epic = "13.8"

            q = epic.strip()
            clean_q = re.sub(r"^(ROADMAP\s*)?§?\s*", "", q, flags=re.I).strip()
            roadmap_slugs: set[str] = set()
            if re.fullmatch(r"\d+(\.\d+)?", clean_q):
                for sec, slug in parse_roadmap_epic_slugs().items():
                    if sec == clean_q or sec.startswith(clean_q + "."):
                        roadmap_slugs.add(slug)

            matched = []
            for t in all_t:
                e = t.get("epic") or ""
                if not e:
                    continue
                if re.fullmatch(r"\d+(\.\d+)?", clean_q):
                    if re.search(rf"§\s*{re.escape(clean_q)}(\.|\b)", e) or (e.lower() in roadmap_slugs):
                        matched.append(t)
                elif q.lower() in e.lower() or q.lower() in t.get("title", "").lower():
                    matched.append(t)
            if not matched:
                print(f"\u26a0\ufe0f no tickets found matching epic query {epic!r}", file=sys.stderr)
                return {}
            name = epic_key(matched[0].get('epic', ''))
            return build_dynamic_plan(matched, name=name, roadmap=name)

        if tickets_filter:
            tids = [x.strip() for x in (tickets_filter.split(",") if isinstance(tickets_filter, str) else tickets_filter)]
            matched = [by_id[tid] for tid in tids if tid in by_id]
            missing = [tid for tid in tids if tid not in by_id]
            if missing:
                print(f"\u26a0\ufe0f ticket(s) not found in queue: {', '.join(missing)}", file=sys.stderr)
            return build_dynamic_plan(matched, name=f"Ticket Set ({len(matched)} tickets)", roadmap="")

        if tag:
            matched = [t for t in all_t if any(tag_matches(x, tag) for x in t.get("tags", []))]
            if not matched:
                print(f"\u26a0\ufe0f no tickets found matching tag {tag!r}", file=sys.stderr)
                return {}
            return build_dynamic_plan(matched, name=f"Tag family — {tag}", roadmap="")

    # Named plan requested:
    if plan_name:
        plan = (conf.get("plans") or {}).get(plan_name)
        if not plan:
            print(f"❌ plan {plan_name!r} not found in .w0m/sdlc.json -> plans", file=sys.stderr)
            return {"_error": f"plan {plan_name} not found"}
        return plan

    # Check active_plan pointer in config if present:
    active_plan_name = conf.get("active_plan")
    if active_plan_name and "plans" in conf and active_plan_name in conf["plans"]:
        return conf["plans"][active_plan_name]

    return conf.get("current_plan", {}) or {}


def plan_summary(tickets: list[dict], plan: dict | None = None) -> str:
    """The declared plan as a TABLE, in the same columns as `hot` and `sdlc`.

    One row per ticket, grouped by stage, because the question a plan has to answer is *what is
    moving and what has not been touched* — and a stage-level percentage cannot answer it. The
    stage cell carries the stage's own roll-up on its first row so the group total and its members
    are readable together without a second table.

    Rendered LAST in the board (after `sdlc`) at the owner's request: they read the report bottom
    up, and the plan is the thing they want under the cursor when scrolling stops.

    ⚠️ `exit` criteria are listed BELOW the table, not squeezed into a cell. They are the sentence
    that actually closes a stage, and truncating them into a column would turn the one piece of
    non-derivable judgement in this block into ellipsis.
    """
    if plan is None:
        plan = load_plan(tickets=tickets)
    if not plan or "_error" in plan or not plan.get("stages"):
        return ""
    active = plan.get("active_stage")
    by_id = {t["id"]: t for t in tickets}

    p_name = plan.get('name', '(unnamed)')
    p_rm = plan.get('roadmap', '')
    hdr = f"▶ EPIC — {p_name}" + (f" · {p_rm}" if p_rm and p_rm not in p_name else "")
    out = [hdr,
           "| Stage | Ticket | Issue | Prio | Status | Area | ACs | Done | Title |",
           "|---|---|---|---|---|---|---|---|---|"]
    exits = []
    for st in plan["stages"]:
        ids = st.get("tickets") or []
        d = t = 0
        for tid in ids:
            a, b = ac_progress(tid)
            d += a
            t += b
        pct = int(round(100 * d / t)) if t else 0
        mark = "\u25b6 " if st.get("id") == active else ""
        lock = " \U0001f512" if st.get("blocking") else ""
        # T231/stage-0 — a recorded closure is shown, because `active_stage` moving on says only
        # "we are working elsewhere", never "this exit was met". Rendered from `exit_met`, and the
        # DATE travels with it: a closure whose age is invisible is one nobody re-checks.
        met = (st.get("exit_met") or {}).get("date")
        seal = f" \u2705 exit met {met}" if met else ""
        st_name = _md_trunc(st.get("name", ""), 34)
        head = f"{mark}**{st.get('id')}** {st_name}{lock}{seal} \u2014 {d}/{t} ({pct}%)"
        for j, tid in enumerate(ids):
            cell = head if j == 0 else "\u21b3"
            tk = by_id.get(tid)
            if tk is None:
                # Named in the plan, absent from the queue. A row, never a silent omission:
                # dropping it shrinks the stage's denominator and flatters it.
                out.append(f"| {cell} | \u2753 {tid} | \u2014 | \u2014 | **NOT FOUND** | \u2014 | \u2014 | \u2014 | "
                           f"declared in the plan, no such ticket |")
                continue
            a, b = ac_progress(tid)
            tpct = int(round(100 * a / b)) if b else 0
            bar = "\u2588" * round(tpct / 10) + "\u2591" * (10 - round(tpct / 10))
            acs = f"{a}/{b}" if b else "\u2014"
            area = tk.get("area") or "—"
            out.append(
                f"| {cell} | {_ticket_link(tk)} | {_issue_link(tk)} | {tk['priority'] or '\u2014'} | "
                f"{tk['status']} | {area} | {acs} | `{bar}` {tpct}% | {_md_trunc(tk['title'], 52)} |")
        if not ids:
            out.append(f"| {head} | \u2014 | \u2014 | \u2014 | \u2014 | \u2014 | \u2014 | \u2014 | no tickets declared |")
        if st.get("exit"):
            exits.append(f"  \u00b7 **{st.get('id')}** \u2014 {st['exit']}")
            em = st.get("exit_met") or {}
            if em.get("date"):
                exits.append(f"    \u2705 **MET {em['date']}** via `{em.get('verified_by','?')}`")
                for ev in em.get("evidence") or []:
                    exits.append(f"       \u00b7 {ev}")
                if em.get("does_not_cover"):
                    exits.append(f"       \u26a0\ufe0f  {em['does_not_cover']}")

    out.append("")
    out.append("  **Exit criteria** \u2014 what actually closes each stage:")
    out.extend(exits)
    out.append("")
    out.append("  \u26a0\ufe0f  The percentages are ACCEPTANCE CRITERIA, i.e. evidence of work \u2014 NOT stage")
    out.append("     completion. A stage at 100% with an unmet `exit` is not done, and the blocking")
    out.append("     stage's exit is a probe result: ticking a box is a claim, running the probe is evidence.")
    return "\n".join(out) + "\n"


def stage_verdict(st: dict, rs: list[dict]) -> str:
    """One stage's verdict from its check results. Pure, so every branch can be PROVEN to fire —
    the same reason `malformed_rows` and the watchdog's `evaluate` were extracted from their mains.

    🔴 The branch worth extracting for: a stage that RECORDED `exit_met` and now has a failing
    condition is not the same event as one that never passed. Something already proven has broken.
    Rendered identically, only one of them is a regression, and it is the one nobody would chase.
    """
    if not rs:
        return "\u26aa no checks declared"
    if any(r["state"] == "FAIL" for r in rs):
        met = (st.get("exit_met") or {}).get("date")
        if met:
            return f"\U0001f6a8 REGRESSION \u2014 recorded MET on {met}, a condition now FAILS"
        return "\u274c NOT MET"
    if any(r["state"] == "UNCHECKED" for r in rs):
        n = sum(r["state"] == "UNCHECKED" for r in rs)
        return f"\u26aa CANNOT BE CONFIRMED \u2014 {n} condition(s) unchecked"
    return "\u2705 MET"


def run_exit_checks(plan: dict) -> dict[str, list[dict]]:
    """Execute each stage's declared `exit_checks` and report what they actually prove.

    🔴 THE RULE, and it is the whole of AC7: a stage's exit is MET only when EVERY condition has a
    command AND every command exits 0. A condition with no command is **UNCHECKED**, and unchecked
    BLOCKS the stage from reporting met — it is not neutral and it does not round down to "the rest
    passed". The alternative is a stage that declares itself complete on the strength of whichever
    conditions someone happened to automate, which is a worse lie than printing prose.

    ⚠️ The command matters as much as its existence. `just authz-probe` is ADVISORY and exits 0 even
    with RED probes; only `--enforce` carries a meaningful code (measured: bare=0, --enforce=1 with
    1 RED outstanding). A check wired to the bare form would be incapable of failing — the vacuous
    gate this estate keeps re-shipping, installed inside the tool built to expose it.
    """
    import shlex
    import subprocess
    out: dict[str, list[dict]] = {}
    for st in plan.get("stages", []):
        rows = []
        for c in st.get("exit_checks") or []:
            cmd = c.get("command")
            if not cmd:
                rows.append({"claim": c["claim"], "state": "UNCHECKED",
                             "detail": c.get("why_unchecked", "no reason recorded")})
                continue
            try:
                # `shlex.split` + shell=False, NOT shell=True. The command comes from a
                # git-tracked, reviewed config, but a checker that spawns a shell propagates the
                # caller's environment into it and turns any future config edit into an execution
                # surface. These commands are `just <recipe> [flags]` — no shell features needed,
                # so the shell buys nothing and costs the whole class. (Caught by semgrep's
                # subprocess-shell-true rule, which was right to block it.)
                # 🔴 `just` MUST run from w0m-api, not w0m-web. The justfile is a SYMLINK to
                # w0m-api's and many recipes use bare `scripts/…` / `supabase/…` paths that only
                # resolve there — the same rule CLAUDE.md states for deploy. Running from w0m-web
                # made `just db-restore-verify` exit 1 with "can't open file
                # w0m-web/scripts/db_restore_verify.py", and the plan reported stage-0 NOT MET on
                # a check that passes everywhere else. ⚠️ A false RED here is as damaging as a
                # false green: it would have sent someone to debug a working backup.
                # w0m_audit.py already uses cwd=API_ROOT for exactly this reason.
                api_root = WORKSPACE_ROOT / "w0m-api"
                argv = shlex.split(cmd)
                # 🔴 shell=False means a shell OPERATOR is not an operator here — it arrives as a
                # literal argument. stage-1 declared `just A && just B`, so `just` was handed a
                # recipe named `&&`, exited 1, and the plan printed ❌ FAIL as though the client
                # funnel were broken. Both suites passed the whole time; the pair had never been
                # RUN. A command this runner cannot honour is UNMEASURED, and unmeasured must not
                # wear the same glyph as measured-and-failing (T242). UNCHECKED is the honest
                # state and already blocks the stage from reporting MET.
                shell_ops = [t for t in argv if t in {"&&", "||", ";", "|", "&", ">", ">>", "<"}]
                if shell_ops:
                    rows.append({"claim": c["claim"], "state": "UNCHECKED",
                                 "detail": f"`{cmd}` — this runner is shell-free by design, so "
                                           f"{shell_ops[0]!r} cannot be honoured. Declare one "
                                           f"exit_check per command."})
                    continue
                r = subprocess.run(argv, capture_output=True, text=True,
                                   timeout=600, cwd=str(api_root))
                rows.append({"claim": c["claim"],
                             "state": "PASS" if r.returncode == 0 else "FAIL",
                             "detail": f"`{cmd}` exit {r.returncode}"})
            except subprocess.TimeoutExpired:
                rows.append({"claim": c["claim"], "state": "FAIL", "detail": f"`{cmd}` TIMED OUT"})
            except OSError as exc:
                rows.append({"claim": c["claim"], "state": "FAIL", "detail": f"`{cmd}` — {exc}"})
        out[st.get("id", "?")] = rows
    return out


def cmd_plan(tickets: list[dict], check: bool = False, plan: dict | None = None) -> int:
    """Progress against the ONE thing the estate decided to ship — T147/§33 or dynamic epic/ticket set.

    🔴 Deliberately NOT a third ranking. `hot` and `sdlc` rank the whole queue against
    generic questions; this measures a NAMED, DECLARED subset against a plan. The number that
    matters here is not "which ticket is best" but "is the thing we said we would ship getting
    closer", which no ranking over 155 tickets can answer.

    ⚠️ Ticket completion is reported as EVIDENCE OF WORK, never as stage completion.
    Every stage carries a written `exit` criterion, and the two are printed apart on purpose: this
    estate has repeatedly shipped a green tick that meant "the boxes are ticked", not "the thing
    works". Stage 0's exit is a probe result, and no amount of AC-ticking substitutes for running it.
    """
    prog = plan if plan is not None else load_plan(tickets=tickets)
    if "_error" in prog:
        return 2
    if not prog:
        print("\u2139\ufe0f  no `current_plan` declared in `.w0m/sdlc.json` — nothing to track.")
        print("   That is a legitimate state between programs; declare one to enable this board.")
        return 0

    stages = prog.get("stages") or []
    if not stages:
        print("\u274c `current_plan` is declared but has no stages — refusing to report progress "
              "over an empty plan.", file=sys.stderr)
        return 2

    by_id = {t["id"]: t for t in tickets}
    active = prog.get("active_stage")
    results = run_exit_checks(prog) if check else {}

    p_name = prog.get('name', '(unnamed)')
    p_rm = prog.get('roadmap', '')
    hdr = f"▶ EPIC — {p_name}" + (f"  ·  {p_rm}" if p_rm and p_rm not in p_name else "")
    print(hdr)
    print("  the active epic, not a ranking — `hot`/`sdlc` rank the queue, this tracks ONE thing\n")

    missing: list[str] = []
    for st in stages:
        ids = st.get("tickets") or []
        rows, done_ac, total_ac, closed = [], 0, 0, 0
        for tid in ids:
            t = by_id.get(tid)
            if t is None:
                missing.append(f"{st['id']}:{tid}")
                rows.append((tid, "\u2753 NOT FOUND", 0, 0))
                continue
            d, tot = ac_progress(tid)
            done_ac += d
            total_ac += tot
            if not t["open"]:
                closed += 1
            rows.append((tid, t["status"], d, tot))

        marker = "\u25b6" if st.get("id") == active else " "
        gate = "  \U0001f512 BLOCKING" if st.get("blocking") else ""
        head = f"{marker} {st.get('id')} \u2014 {st.get('name')}{gate}"
        print(f"{head}")
        print(f"    tickets closed {closed}/{len(ids)} \u00b7 acceptance criteria {_bar(done_ac, total_ac)}"
              f" ({done_ac}/{total_ac})")
        for tid, status, d, tot in rows:
            ac = f"{d}/{tot}" if tot else "no ACs"
            print(f"      \u00b7 {tid:<6} {status:<12} {ac}")
        if st.get("exit"):
            print(f"    exit: {st['exit']}")
        for r in (results or {}).get(st.get("id"), []):
            glyph = {"PASS": "\u2705", "FAIL": "\u274c", "UNCHECKED": "\u26aa"}[r["state"]]
            print(f"      {glyph} {r['state']:<9} {r['claim']}")
            print(f"                   {r['detail']}")
        print()

    if missing:
        # A declared ticket that does not exist is drift between the plan and the queue, and it
        # must be loud: silently skipping it would shrink the denominator and make the program
        # look further along than it is — the estate's signature failure, applied to a roadmap.
        print(f"\u274c {len(missing)} declared ticket(s) not found in the queue: "
              f"{', '.join(missing)}", file=sys.stderr)
        print("   The plan references work that has no ticket. Fix the declaration or file the "
              "ticket; do not leave the program measuring a smaller set than it claims.",
              file=sys.stderr)
        return 1

    if check:
        print("  \u2500\u2500 exit verdicts \u2014 a stage is MET only if EVERY condition PASSES:")
        for st in stages:
            print(f"     {st.get('id'):<9} {stage_verdict(st, results.get(st.get('id'), []))}")
        print()
    print("  \u26a0\ufe0f  Ticket progress is EVIDENCE OF WORK, not stage completion. Each stage's")
    print("     `exit` is the criterion that actually closes it, and Stage 0's is a probe result \u2014")
    print("     ticking an acceptance criterion is a claim; running the probe is evidence.")
    return 0


def cmd_overview(tickets: list[dict], top: int) -> int:
    from collections import Counter, defaultdict

    openq = [t for t in tickets if t["open"]]
    n = len(openq)
    # Compute AC progress HERE rather than reusing rank_sdlc's: that function builds `dict(t)`
    # COPIES, so its ac_done/ac_total never reach these ticket objects — reading them back gave
    # every group a silent 0%. Unmeasurable tickets (no ACs) are counted separately instead of
    # being folded in as zeros, which would understate every group it touches.
    for t in openq:
        d, tot = ac_progress(t["id"])
        t["ac_done"], t["ac_total"] = d, tot
    unmeasured = sum(1 for t in openq if not t["ac_total"])
    specced_all = sum(1 for t in tickets if (t.get("spec") or "").strip())
    specced_open = sum(1 for t in openq if (t.get("spec") or "").strip())
    print(f"▶ OVERVIEW — {n} open tickets ({specced_open}/{n} open specced · {specced_all}/{len(tickets)} specced total), grouped four ways")
    print(f"   AC bars cover the {n - unmeasured} measurable ticket(s); "
          f"{unmeasured} have no acceptance criteria and are excluded from them, not scored 0%.\n")

    def block(title: str, key, note: str = "", limit: int = 99) -> None:
        groups: dict[str, list[dict]] = defaultdict(list)
        missing = 0
        for t in openq:
            k = key(t)
            if not k:
                missing += 1
                continue
            groups[k].append(t)
        cov = n - missing
        print(f"── {title} — {len(groups)} group(s) over {cov}/{n} tickets"
              + (f", ⚠️ {missing} unkeyed" if missing else "") + " ──")
        if note:
            print(f"   {note}")
        for k, ts in sorted(groups.items(), key=lambda kv: (-len(kv[1]), kv[0]))[:limit]:
            inprog = sum(1 for t in ts if t["status"] == "in-progress")
            done = sum(t.get("ac_done", 0) for t in ts)
            total = sum(t.get("ac_total", 0) for t in ts)
            ids = " ".join(t["id"] for t in sorted(ts, key=lambda t: -t["score"])[:4])
            print(f"  {len(ts):>3} open · {inprog:>2} wip · {_bar(done, total)} "
                  f"· {k[:34]:<34} {ids}")
        print()

    block("by AREA (theme)", lambda t: t["area"])
    block("by EPIC, rolled up to ROADMAP §N", lambda t: epic_key(t["epic"]),
          note="⚠️ raw `epic:` strings are inconsistent (§13, §13.2, '§13 — … (child of T149)'); "
               "rolled up so one section reads as one theme.", limit=top)

    # Tags are a genuinely weak dimension here and the output should say so rather than imply
    # otherwise: 153 distinct labels over 119 tickets is a long tail, and the single most common
    # one is process metadata, not a theme.
    tagc = Counter(tag for t in openq for tag in t["tags"])
    tagged = sum(1 for t in openq if t["tags"])
    print(f"── by TAG — {len(tagc)} distinct over {tagged}/{n} tickets ──")
    print(f" [WARN] long tail: {sum(1 for c in tagc.values() if c == 1)} tags appear exactly once. "
          f"`backfilled` is process metadata, not a theme — ignore it when reading this.")
    for tag, c in tagc.most_common(top):
        ids = " ".join(t["id"] for t in sorted((x for x in openq if tag in x["tags"]),
                                               key=lambda t: -t["score"])[:4])
        print(f"  {c:>3}  {tag:<22} {ids}")
    print()

    # T353. Namespaced tags (`sdlc`, `sdlc_design`, `sdlc_design_gate`) roll up on their OWN
    # spelling — no manual roadmap-section table to maintain, and a ticket can sit under several
    # families. Only fires for tags that actually carry a `_`; a flat tag isn't given a fake parent.
    t_by_id = {t["id"]: t for t in openq}
    fam_ids: dict[str, set[str]] = defaultdict(set)
    fam_level: dict[str, int] = {}
    for t in openq:
        for tg in t["tags"]:
            for lvl, key in enumerate(tag_family(tg), start=1):
                fam_ids[key].add(t["id"])
                fam_level[key] = lvl

    def _fam_bar(ids: set[str]) -> str:
        done = sum(t_by_id[i].get("ac_done", 0) for i in ids)
        total = sum(t_by_id[i].get("ac_total", 0) for i in ids)
        return _bar(done, total)

    roots = sorted(k for k, lvl in fam_level.items() if lvl == 1
                   and any(fam_level[o] == 2 for o in fam_level if o.startswith(k + "_")))
    if roots:
        print(f"── by TAG FAMILY — namespaced tags auto-rolled-up 1→{TAG_FAMILY_DEPTH} deep "
              f"({len(roots)} root famil{'y' if len(roots) == 1 else 'ies'}) ──")
        print("   Convention: `epic_area` groups under `epic`, `epic_area_topic` under `epic_area` — "
              "computed from the tag string, no lookup table (T353).")
        for root in roots[:top]:
            print(f"  {len(fam_ids[root]):>3} · {_fam_bar(fam_ids[root])} · {root}")
            for child in sorted(k for k, lvl in fam_level.items()
                                 if lvl == 2 and k.startswith(root + "_")):
                print(f"      {len(fam_ids[child]):>3} · {_fam_bar(fam_ids[child])} · {child}")
                for gc in sorted(k for k, lvl in fam_level.items()
                                  if lvl == 3 and k.startswith(child + "_")):
                    ids = " ".join(sorted(fam_ids[gc], key=lambda i: -t_by_id[i]["score"])[:4])
                    print(f"          {len(fam_ids[gc]):>3} · {_fam_bar(fam_ids[gc])} · {gc}  {ids}")
        print()

    # BUNDLES — what would sensibly be worked together. Same area AND same roadmap section is a
    # stronger signal than either alone: it means shared surface and shared intent.
    bundles: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for t in openq:
        if t["area"] and epic_key(t["epic"]):
            bundles[(t["area"], epic_key(t["epic"]))].append(t)
    multi = {k: v for k, v in bundles.items() if len(v) > 1}
    print(f"── BUNDLES — same AREA + same ROADMAP § ({len(multi)} with 2+ members) ──")
    print("   Work these together: shared surface and shared intent, so the context is paid for once.")
    for (area, epic), ts in sorted(multi.items(), key=lambda kv: -len(kv[1]))[:top]:
        done = sum(t.get("ac_done", 0) for t in ts)
        total = sum(t.get("ac_total", 0) for t in ts)
        print(f"  {len(ts):>3} · {_bar(done, total)} · {area:<10} {epic:<16} "
              f"{' '.join(t['id'] for t in sorted(ts, key=lambda t: -t['score']))}")
    return 0


def cmd_area(tickets: list[dict], area_filter: str | None = None) -> int:
    """Render open tickets grouped by functional area, with summary metrics and per-area tables."""
    prio_rank = {"P0": 0, "P1": 1, "P2": 2, "P3": 3, "": 4}
    status_rank = {"in-progress": 0, "queued": 1, "blocked": 2, "paused": 3}

    by_area: dict[str, list[dict]] = defaultdict(list)
    for t in tickets:
        a = t.get("area") or "unassigned"
        by_area[a].append(t)

    if area_filter:
        if area_filter not in by_area:
            print(f"❌ area {area_filter!r} not found in queue.", file=sys.stderr)
            print(f"Available areas: {', '.join(sorted(by_area.keys()))}", file=sys.stderr)
            return 1
        target_areas = [area_filter]
    else:
        target_areas = sorted(by_area.keys(), key=lambda a: (
            -sum(1 for t in by_area[a] if t["open"]),
            -len(by_area[a]),
            a
        ))

    total_open = sum(1 for t in tickets if t["open"])
    total_wip = sum(1 for t in tickets if t["open"] and t["status"] == "in-progress")
    total_done = sum(1 for t in tickets if not t["open"])
    total_all = len(tickets)

    out: list[str] = []
    out.append(f"▶ TASK REGISTRY — GROUPED BY AREA\n")
    out.append(f"  Total Tickets: {total_all} · Open: {total_open} ({total_wip} in progress / WIP) · "
               f"Done: {total_done} ({(total_done/total_all)*100:.1f}%)\n")

    out.append("### Area Breakdown Summary\n")
    out.append("| Area | Open | WIP | Done | Total | % Complete |")
    out.append("|---|---|---|---|---|---|")
    for a in target_areas:
        tlist = by_area[a]
        op = sum(1 for t in tlist if t["open"])
        wip = sum(1 for t in tlist if t["open"] and t["status"] == "in-progress")
        dn = sum(1 for t in tlist if not t["open"])
        tot = len(tlist)
        pct = (dn / tot * 100) if tot > 0 else 0
        out.append(f"| **`{a}`** | {op} | {wip} | {dn} | {tot} | {pct:.0f}% |")

    out.append("\n---\n")

    for a in target_areas:
        tlist = by_area[a]
        open_t = [t for t in tlist if t["open"]]
        done_cnt = sum(1 for t in tlist if not t["open"])
        wip_cnt = sum(1 for t in open_t if t["status"] == "in-progress")

        out.append(f"### Area: `{a}`\n")
        out.append(f"*{len(open_t)} open ({wip_cnt} in-progress) · {done_cnt} done · {len(tlist)} total*\n")

        if not open_t:
            out.append("*(no open tickets in this area)*\n")
            continue

        open_t.sort(key=lambda t: (
            status_rank.get(t["status"], 9),
            prio_rank.get(t["priority"] or "", 9),
            -t.get("score", 0),
            num(t["id"])
        ))

        out.append("| ID | Issue | Prio | Status | Title | Queue | AC | Epic |")
        out.append("|---|---|---|---|---|---|---|---|")
        for t in open_t:
            d, tot = ac_progress(t["id"])
            ac_str = f"{d}/{tot}" if tot > 0 else "—"
            q = t.get("queue") or ""
            q_str = f"`{q}`" if q else "—"
            ep = (t.get("epic") or "—").replace("|", "\\|").strip()
            title_clean = t["title"].replace("\n", " ").replace("|", "\\|").strip()
            out.append(
                f"| {_ticket_link(t)} | {_issue_link(t)} | `{t['priority'] or '—'}` | "
                f"`{t['status']}` | {_md_trunc(title_clean, 52)} | {q_str} | {ac_str} | {ep} |"
            )
        out.append("")

    emit("\n".join(out))
    return 0


