# ── the scoring model, stated in one place so it can be argued with ──────────
PRIORITY_WEIGHT = {"P0": 100, "P1": 60, "P2": 25, "P3": 10, "": 15}
STATUS_WEIGHT = {
    "in-progress": 25,   # already moving — cheapest to advance
    "queued": 0,
    "blocked": -30,      # cannot be acted on right now, whatever its priority
    "paused": -40,       # deliberately parked; surfacing it as "hot" is noise
}
BLOCKED_BY_WEIGHT = -35  # an OPEN blocker means it cannot be started — see `blockers()` below
SPEC_BONUS = 15          # a live, validated spec means the expensive part is already paid
ROWLESS_BONUS = 10       # invisible on the queue humans read → deserves attention
AGE_PER_WEEK = 1
AGE_CAP = 10
DONE = ("done", "archived")


def frontmatter(path: Path) -> dict:
    """Parse the ticket's YAML-ish frontmatter.

    ⚠️ Inline comments are REAL here and must be stripped. Several tickets carry
    `status: done          # queued | in-progress | blocked | done | paused` — a legend beside the
    value. Naively taking everything after the colon yields the string
    "done          # queued | ..." which matches NO status, so those tickets read as OPEN and the
    first run of this tool ranked three finished P0s as the hottest work in the estate.
    A quoted value keeps its `#`; an unquoted one is cut at the first ` #`.
    """
    text = path.read_text(errors="ignore")
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end == -1:
        return {}
    out: dict = {}
    for line in text[3:end].splitlines():
        m = re.match(r"^([a-z0-9_]+):\s*(.*)$", line.strip())
        if not m:
            continue
        key, raw = m.group(1), m.group(2).strip()
        if raw.startswith('"') and raw.endswith('"') and len(raw) >= 2:
            value = raw[1:-1].replace('\\"', '"')
        elif raw.startswith("'") and raw.endswith("'") and len(raw) >= 2:
            value = raw[1:-1].replace("\\'", "'")
        elif raw[:1] in ("\"", "'"):
            m_q = re.match(r"^(['\"])(.*?)(?<!\\)\1(?:\s+#.*)?$", raw)
            if m_q:
                value = m_q.group(2).replace('\\"', '"') if m_q.group(1) == '"' else m_q.group(2).replace("\\'", "'")
            else:
                q = raw[0]
                closing = raw.find(q, 1)
                value = raw[1:closing] if closing > 0 else raw[1:]
        else:
            value = re.split(r"\s+#", raw, maxsplit=1)[0].strip()
        out[key] = value
    return out


def rows_in_tasks_md() -> set[str]:
    if not TASKS_MD.exists():
        return set()
    # Accepts BOTH the bare form (`| T160 |`) and the linked form
    # (`| [T160](project/tickets/T160.md) · [#157](…) |`). The board carries both links so a
    # reader can reach the ticket file or the issue from the row; a parser that only knew the
    # bare form would report every row as rowless the moment the board gained links.
    return set(re.findall(r"^\|\s*(?:\[\s*)?[*_`]*\s*(T\d+[a-z]?)[*_`]*\s*(?:\]|\|)", TASKS_MD.read_text(), re.M))


# ── blockers ─────────────────────────────────────────────────────────────────
# 🔑 `blocked_by:` is DECLARED and almost nobody declares it: measured 2026-08-27, **2** open
# tickets carry the field while **29** name a blocker in their acceptance criteria. T173 added the
# field precisely because "this relationship lived in PROSE where no board could see it" — and then
# the prose stayed. So the boards read both: the field, and the ACs.
#
# NARROW ON PURPOSE. An AC counts only when ALL of these hold:
#   1. it is UNTICKED — a met criterion is not a blocker, whatever it says;
#   2. it names another ticket as `[[T…]]`;
#   3. that same AC uses blocking language;
#   4. the named ticket is itself OPEN — a dependency on finished work is not a block.
# A looser scan over whole ticket bodies returns 28 of ~190 open tickets, many of them merely
# discussing other work. This returns 15, and the two independently-known cases land exactly:
# T198 → T117/T200 and T22 → T8, the latter matching the only real declared field in the corpus.
# ⚠️ Rule 4 is what keeps it honest over time — T284's AC says "[[T283]] must land first", and T283
# closing on 2026-08-27 removed the block without anyone editing the AC.
BLOCK_PHRASE = re.compile(
    r"(blocked (?:on|by)|depends on|prerequisite|cannot be (?:built|done|landed|closed)"
    r"|until\b|awaiting|stands? between|blocker)", re.I)
TICKET_REF = re.compile(r"\[\[(T[0-9a-z]+)\]\]")


def _unticked_acs(text: str) -> list[str]:
    """Each unticked AC as one blob — its own line plus indented continuations.

    The continuation matters: most ACs here state the dependency two or three lines in, so a
    line-by-line scan would miss the majority of real blockers.
    """
    out: list[str] = []
    cur: str | None = None
    for line in text.splitlines():
        if re.match(r"^- \[ \]", line):
            if cur is not None:
                out.append(cur)
            cur = line
        elif re.match(r"^- \[[x~N]", line) or re.match(r"^#{2,3} ", line):
            if cur is not None:
                out.append(cur)
            cur = None
        elif cur is not None and (line.startswith("  ") or not line.strip()):
            cur += "\n" + line
        elif cur is not None:
            out.append(cur)
            cur = None
    if cur is not None:
        out.append(cur)
    return out


def blockers(open_ids: set[str]) -> dict[str, dict[str, list[str]]]:
    """-> {tid: {"declared": [...], "inferred": [...]}}, both filtered to OPEN blockers."""
    out: dict[str, dict[str, list[str]]] = {}
    for path in sorted(TICKETS.glob("T*.md")):
        tid = path.stem
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        head, _, body = text.partition("---")[2].partition("---")[0], None, text
        declared = []
        m = re.search(r"^blocked_by:[ \t]*(.*)$", head, re.M)
        if m:
            declared = [b for b in re.findall(r"T[0-9a-z]+", m.group(1))
                        if b != tid and b in open_ids]
        inferred: set[str] = set()
        acs = re.search(r"## Acceptance criteria(.*?)(?=\n## )", body, re.S)
        if acs:
            for ac in _unticked_acs(acs.group(1)):
                if not BLOCK_PHRASE.search(ac):
                    continue
                inferred |= {r for r in TICKET_REF.findall(ac) if r != tid and r in open_ids}
        inferred -= set(declared)
        if declared or inferred:
            out[tid] = {"declared": sorted(declared), "inferred": sorted(inferred)}
    return out


def load(today: date | None = None) -> list[dict]:
    today = today or date.today()
    rows = rows_in_tasks_md()
    # A blocker only blocks while it is itself open, so the open set is needed before scoring —
    # hence the pre-pass. Cheap (one frontmatter read per ticket) and it keeps `blockers()` pure.
    open_ids = {fm["id"] for fm in (frontmatter(q) for q in sorted(TICKETS.glob("T*.md")))
                if fm.get("id") and fm.get("status", "") not in DONE}
    blk = blockers(open_ids)
    out = []
    for path in sorted(TICKETS.glob("T*.md")):
        fm = frontmatter(path)
        if not fm.get("id"):
            continue
        status = fm.get("status", "")
        prio = fm.get("priority", "") or ""
        if prio.lower() in ("none", "null"):
            prio = ""
        age_weeks = 0
        created = fm.get("created", "")
        try:
            age_weeks = max(0, (today - datetime.strptime(created, "%Y-%m-%d").date()).days // 7)
        except Exception:  # noqa: BLE001
            pass
        rowless = fm["id"] not in rows
        parts = {
            "priority": PRIORITY_WEIGHT.get(prio, PRIORITY_WEIGHT[""]),
            "status": STATUS_WEIGHT.get(status, 0),
            "spec": SPEC_BONUS if fm.get("spec") else 0,
            "rowless": ROWLESS_BONUS if rowless else 0,
            "age": min(age_weeks * AGE_PER_WEEK, AGE_CAP),
            # HOT answers "what can be STARTED", so an open blocker is the most direct possible
            # answer of "not this". Until 2026-08-27 only `status: blocked` was penalised, and
            # exactly two tickets in the corpus ever set it — so the board ranked T198 second
            # while two of its remaining ACs belonged to unbuilt work in other tickets.
            "blocked_by": BLOCKED_BY_WEIGHT if blk.get(fm["id"]) else 0,
        }
        out.append({
            "id": fm["id"],
            "title": fm.get("title", ""),
            "status": status,
            "priority": prio,
            "spec": fm.get("spec", ""),
            "repos": fm.get("repos", ""),
            "gh_issue": fm.get("gh_issue", "0"),
            "blockers": blk.get(fm["id"], {"declared": [], "inferred": []}),
            # T163 — grouping dimensions for `tasks overview`. Captured raw and normalised at
            # display time, never at load, so the overview can SHOW the drift (three spellings of
            # ROADMAP §13) instead of silently merging it away.
            "epic": (fm.get("epic", "") or "").strip('"'),
            "area": fm.get("area", ""),
            "queue": fm.get("queue", ""),
            "agent_id": (fm.get("agent_id", "") or "").strip('"'),
            "tags": [t for t in re.findall(r"[\w-]+", fm.get("tags", "")) if t],
            "created": created,
            "rowless": rowless,
            "open": status not in DONE,
            "score": sum(parts.values()),
            "parts": parts,
        })
    return out


def num(tid: str) -> int:
    return int(re.sub(r"\D", "", tid) or 0)


# ── SDLC progress ────────────────────────────────────────────────────────────
# `hot` answers "what can be WORKED" — readiness × consequence from recorded fields. It is
# deliberately blind to how FINISHED a ticket is, which is a real gap: T151 sat at 8 of 9 ACs
# and never appeared in the top 10, and T127 reads identically at 5 ACs done and at 6.
# `sdlc` answers the complementary question: "what is closest to DONE, weighted by priority" —
# i.e. what is worth finishing rather than what is worth starting.
# Bold is OPTIONAL (`\*{0,2}`) and a digit is REQUIRED after AC. Requiring `**AC` silently
# excluded NINE tickets that wrote criteria as `- [ ] AC1 — …`, an entirely ordinary style; they
# reported (0,0) and were dropped from the sdlc ranking as "unmeasurable", indistinguishable from
# tickets that never wrote any. The digit keeps ordinary checklist prose (`- [ ] ACCESS review`)
# from being mistaken for a criterion.
# Four states, not two. Matching only [x]/[ ] is what let T125 report **4/4 = 100%** while one AC
# was explicitly blocked: it also used [N/A] and [~], so those lines were invisible and the
# denominator collapsed onto exactly the completed ones. An earlier session hit the same bug from
# the other side (4/5 = 80%) and worked around it by changing a checkbox to [N/A] — converting an
# undercount into a FALSE GREEN. Its own note said "worth fixing in the ranker, not just here".
AC_ANY = re.compile(r"^\s*-\s*\[(x|X| |~|N/A)\]\s*\*{0,2}AC\d", re.M)
AC_DONE = re.compile(r"^\s*-\s*\[[xX]\]\s*\*{0,2}AC\d", re.M)
# [N/A] = a conditional whose branch was not taken. It is not outstanding work, so it counts
# toward NEITHER done nor total — leaving it in the denominator would permanently cap the ticket
# below 100% and make a finished ticket look unfinished.
AC_NA = re.compile(r"^\s*-\s*\[N/A\]\s*\*{0,2}AC\d", re.M)


def ac_progress(tid: str) -> tuple[int, int]:
    """(done, total) acceptance criteria for a ticket, counted from its own file.

    Understands four states: `[x]` done, `[ ]` open, `[~]` half-done, `[N/A]` not-applicable.
    `[N/A]` is excluded from both counts; everything else counts toward the total. A ticket
    with NO ACs returns (0, 0) and is EXCLUDED from the sdlc ranking rather than scored 0% —
    unmeasurable is not the same as unstarted, and ranking 0/0 as "no progress" would flood the
    table with tickets that simply never wrote acceptance criteria.
    """
    p = TICKETS / f"{tid}.md"
    try:
        body = p.read_text(encoding="utf-8")
    except OSError:
        return (0, 0)
    done = len(AC_DONE.findall(body))
    total = len(AC_ANY.findall(body)) - len(AC_NA.findall(body))
    # `[~]` (half done) lands in `total` but not `done`, which is the point: a partially finished
    # criterion is not a finished one, and it must hold the ticket below 100%.
    return (done, total)


def rank_sdlc(tickets: list[dict], n: int, priority: str | None = None) -> list[dict]:
    """Rank OPEN tickets by how close they are to done, weighted by priority.

    score = completion% + priority weight. A P0 at 90% outranks a P1 at 90%, and both outrank a
    P0 at 10% — because the question is "what should I finish", not "what should I start".
    """
    pool = [t for t in tickets if t["open"] and t["status"] not in ("paused",)]
    if priority:
        pool = [t for t in pool if t["priority"].upper() == priority.upper()]
    out = []
    for t in pool:
        done, total = ac_progress(t["id"])
        if total == 0:
            continue  # unmeasurable — see ac_progress()
        pct = round(100 * done / total)
        row = dict(t)
        row["ac_done"], row["ac_total"], row["ac_pct"] = done, total, pct
        row["sdlc_score"] = pct + PRIORITY_WEIGHT.get(t["priority"], PRIORITY_WEIGHT[""])
        out.append(row)
    return sorted(out, key=lambda t: (-t["sdlc_score"], -t["ac_pct"], num(t["id"])))[:n]


def apply_cross_tree_radar(
    tickets: list[dict],
    *,
    include_claimed: bool = False,
    agent_filter: str | None = None,
    work_root: Path | None = None,
    registry_path: Path | None = None,
) -> tuple[list[dict], list[dict], str]:
    """Scan sibling `~/.w0m/work/*` trees + registry for virtual agent claims/completions (T564 AC4)."""
    web_scripts = WEB_ROOT / "project" / "scripts"
    if str(web_scripts) not in sys.path:
        sys.path.insert(0, str(web_scripts))
    try:
        import agent_identity as ai
    except ImportError:
        return tickets, [], "agent:main"

    my_agent = ai.resolve_agent_id(workspace_root=WORKSPACE_ROOT, work_root=work_root)
    claims = ai.scan_cross_tree_claims(
        workspace_root=WORKSPACE_ROOT,
        work_root=work_root,
        registry_path=registry_path,
    )
    target_agent = ai.normalize_virtual_id(agent_filter) if agent_filter else None
    target_tag = ai.agent_id_to_tag(target_agent) if target_agent else None

    excluded: list[dict] = []
    out: list[dict] = []
    for t in tickets:
        row = dict(t)
        c = claims.get(row["id"])
        if c:
            row["virtual_claim"] = c
            if not row.get("agent_id") and c.get("agent_id"):
                row["agent_id"] = c["agent_id"]
        if target_agent:
            if row.get("agent_id") != target_agent and target_tag not in row.get("tags", []):
                continue
        elif row["open"] and c and not include_claimed:
            c_status = c.get("status", "")
            c_agent = c.get("agent_id", "")
            # Exclude if already completed in a sibling tree, or actively owned by another virtual agent
            if c_status in DONE or (c_agent and c_agent != my_agent and c_status in ("in-progress", "claimed")):
                row["cross_tree_excluded"] = True
                excluded.append({
                    "id": row["id"],
                    "agent_id": c_agent,
                    "status": c_status,
                    "source": c.get("source", ""),
                    "title": row["title"],
                })
        out.append(row)
    return out, excluded, my_agent


def rank(tickets: list[dict], n: int, priority: str | None = None,
         status: str | None = None, include_blocked: bool = False,
         exclude_cross_tree: bool = False) -> list[dict]:
    pool = [t for t in tickets if t["open"]]
    if exclude_cross_tree:
        pool = [t for t in pool if not t.get("cross_tree_excluded")]
    if priority:
        pool = [t for t in pool if t["priority"].upper() == priority.upper()]
    if status:
        pool = [t for t in pool if t["status"] == status]
    if not include_blocked and not status:
        pool = [t for t in pool if t["status"] not in ("paused",)]
    return sorted(pool, key=lambda t: (-t["score"], num(t["id"])))[:n]


def fmt_table(rows: list[dict], show_parts: bool) -> str:
    if not rows:
        return "  (no matching open tickets)"
    lines = []
    head = "  #  score  id     prio  status        title"
    lines.append(head)
    lines.append("  " + "-" * (len(head) - 2))
    for i, t in enumerate(rows, 1):
        flag = " ⚠rowless" if t["rowless"] else ""
        spec = " 📄spec" if t["spec"] else ""
        lines.append(
            f"  {i:<2} {t['score']:>5}  {t['id']:<6} {t['priority'] or '—':<5} "
            f"{t['status']:<13} {_md_trunc(t['title'], 58)}{spec}{flag}")
        if show_parts:
            p = t["parts"]
            lines.append(
                f"          └ prio {p['priority']:+} · status {p['status']:+} · "
                f"spec {p['spec']:+} · rowless {p['rowless']:+} · age {p['age']:+}")
    return "\n".join(lines)


