#!/usr/bin/env python3
"""Queue query + ranking (T146) — `just tasks hot`, `just tasks list --priority P2`.

WHY THIS EXISTS
    "What are the top 10 hot?" was answered by an agent re-deriving it from prose every session, and
    then hand-writing the result into STATE.md. That has two failure modes: the ranking silently
    reflects whichever agent wrote it, and the written list is stale the moment a ticket moves. Both
    happened repeatedly — a recorded hot-list entry was still claiming "29 fileless tickets" after
    they had been fixed.

    So the ranking is computed from MECHANICAL SIGNALS, the score components are PRINTED, and the
    output is regenerated by the SDLC gates rather than typed.

⚠️ WHAT THIS IS NOT
    This is a HEURISTIC, not judgement. It cannot know that a P2 is suddenly urgent because a
    customer asked, or that a P0 is parked pending someone's reply. It ranks readiness × consequence
    from what the tickets actually record. **Disagree with it freely** — but disagree with a visible
    score, which is the point. Every row shows its components so a human can see exactly why it
    placed where it did.

    Corollary: a ticket blocked on an owner action scores LOW here even when it matters enormously,
    because this tool measures what can be *worked*, not what is important. Read the `blocked`/
    `paused` rows as a separate list, not as "unimportant".
"""

