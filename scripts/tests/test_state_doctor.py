#!/usr/bin/env python3
"""T145 AC9 — prove the STATE.md staleness gate can actually FAIL.

`state-check` runs on every push and has fired at me repeatedly. The logic is sound and even
carries its own empty-set discipline — but nothing had ever demonstrated it failing, and AC9 says
it plainly: *a staleness gate that cannot fail is worse than no gate, because it certifies a stale
file.*

Two proofs are demanded and both are here: hand-edit a recorded exit code and observe exit 1, and
show it FAILS rather than passes when the managed block is absent or empty.

Driven against a FIXTURE STATE.md via `W0M_STATE_MD` — proving this against the real file would
mean committing a knowingly-wrong handoff surface. The fixture is generated by the tool's own
`--write`, so the control case is a file the tool itself considers correct; without that control,
every failing case below could be failing for the wrong reason.

Run: `just state-doctor-test`
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WEB = ROOT / "wom7web"
SCRIPT = ROOT / "scripts" / "state_doctor.py"
TMP = Path(tempfile.mkdtemp(prefix="t145-ac9-"))

failures: list[str] = []

# Captured BEFORE anything runs, so the final assertion that no probe touched the real handoff
# surface is a measurement rather than a hope.
import hashlib as _hl  # noqa: E402
LIVE_HASH_AT_START = _hl.sha256((ROOT / "STATE.md").read_bytes()).hexdigest()


def check(label: str, ok: bool, detail: str = "") -> None:
    print(f"  {'✅' if ok else '❌'} {label}")
    if not ok:
        failures.append(f"{label}{(' — ' + detail) if detail else ''}")


if not SCRIPT.is_file():
    print("❌ state_doctor.py missing — the suite cannot prove anything")
    sys.exit(2)


def run(path: Path, *args) -> subprocess.CompletedProcess:
    env = {
        **os.environ,
        "W0M_STATE_MD": str(path),
        "W0M_STATE_FACTS_CACHE": str(TMP / "facts_cache.json"),
    }
    return subprocess.run([sys.executable, str(SCRIPT), *args],
                          capture_output=True, text=True, env=env)


print("\n── 🔴 superseded PICKUP blocks rotate; the newest never does ──")
# The bug this pins: `rotate_patterns` expected `### ⭐ (was) PICK UP HERE`, a heading something used
# to rewrite — 17 archived files carry that form and STATE.md carried ZERO. Meanwhile `never_rotate`
# protected `^## ⭐ PICK UP HERE`, shielding the superseded ones too. So the file held FOUR pickup
# blocks (two both claiming "(LATEST)") and rotation could never fire, at 94% of the byte cap.
_pk = TMP / "pickup"
_pk.mkdir(exist_ok=True)
_src = (ROOT / "STATE.md").read_text(encoding="utf-8")
_head = _src.split("## ⭐ PICK UP HERE")[0]
_fix = _pk / "STATE.md"
_fix.write_text(_head
    + "## ⭐ PICK UP HERE — 2026-08-10 — oldest\n\nbody a\n\n"
    + "## ⭐ PICK UP HERE — 2026-08-20 — NEWEST\n\nbody c\n\n"      # deliberately NOT last
    + "## ⭐ PICK UP HERE — 2026-08-14 — middle\n\nbody b\n", encoding="utf-8")
for _d in ("state-archive",):
    (_pk / "project" / _d).mkdir(parents=True, exist_ok=True)
(_pk / "project/state-archive/DISPOSITION.md").write_text("# disposition\n\n| key | d | why |\n|---|---|---|\n", encoding="utf-8")
_r = run(_fix, "--rotate")
_after = _fix.read_text(encoding="utf-8")
check("rotate moves the superseded pickup blocks", "2 section(s) moved" in (_r.stdout + _r.stderr),
      (_r.stdout + _r.stderr)[-200:])
check("the NEWEST block survives", "2026-08-20 — NEWEST" in _after)
# ⚠️ Assert on the BODY, not the title. A rotated section leaves an archive INDEX row naming it —
# that is T174's design, the index is how history stays reachable — so "the title is gone" is false
# by construction. The first version of these two probes checked the title and failed against
# working code, which is the same shape as the day's other probe bugs: a substring standing in for
# the thing it is meant to represent.
check("...even though it was not last in the file (ordered by DATE, not position)",
      "2026-08-20 — NEWEST" in _after and "body a" not in _after)
check("the older blocks' BODIES are gone from STATE.md",
      "body a" not in _after and "body b" not in _after and "body c" in _after)
check("...but the archive index still NAMES them (history stays reachable)",
      "2026-08-10-pickup" in _after and "2026-08-14-pickup" in _after)
_r2 = run(_fix, "--rotate")
check("a second run moves nothing (idempotent)", "0 section(s) archived" in (_r2.stdout + _r2.stderr),
      (_r2.stdout + _r2.stderr)[-160:])
_single = _pk / "STATE-one.md"
_single.write_text(_head + "## ⭐ PICK UP HERE — 2026-08-20 — only one\n\nbody\n", encoding="utf-8")
_r3 = run(_single, "--rotate")
check("a file with ONE pickup block rotates none of it",
      "2026-08-20 — only one" in _single.read_text(encoding="utf-8"))

print("\n── --brief: the session-start read is the CURRENT pickup block, and fails when there is none ──")
# Reuses the three-block fixture from above, BEFORE rotation touched it, so "newest by date, not
# position" is proven here too — the brief and rotation must agree on which block is live.
_bf = _pk / "STATE-brief.md"
_bf.write_text(_head
    + "## ⭐ PICK UP HERE — 2026-08-10 — oldest\n\nbody a\n\n"
    + "## ⭐ PICK UP HERE — 2026-08-20 — NEWEST\n\nbody c\n\n"
    + "## ⭐ PICK UP HERE — 2026-08-14 — middle\n\nbody b\n", encoding="utf-8")
(_pk / ".tasks").mkdir(exist_ok=True)
(_pk / ".tasks" / "T901.md").write_text(
    "---\nid: T901\nstatus: in-progress\n---\n\n## Status notes\n\n"
    "- 2026-08-01 — older note\n- **2026-08-09 — newest note wins**\n", encoding="utf-8")
(_pk / ".tasks" / "T902.md").write_text(
    "---\nid: T902\nstatus: in-progress\n---\n\n## Status notes\n\nno dated lines here\n", encoding="utf-8")
(_pk / ".tasks" / "T903.md").write_text(
    "---\nid: T903\nstatus: done\n---\n\n## Status notes\n\n- 2026-08-09 — finished\n", encoding="utf-8")
_r = run(_bf, "--brief")
check("--brief exits 0 when a pickup block exists", _r.returncode == 0, (_r.stdout + _r.stderr)[-200:])
check("...lists an in-progress ticket with its NEWEST dated note, not its first",
      "T901" in _r.stdout and "newest note wins" in _r.stdout and "older note" not in _r.stdout,
      _r.stdout[:400])
check("...lists an in-progress ticket with NO note as such, rather than omitting it",
      "T902" in _r.stdout and "NO status note" in _r.stdout, _r.stdout[:400])
check("...and leaves out tickets that are not in-progress", "T903" not in _r.stdout)
check("...and prints the NEWEST block by date, not the last by position",
      "body c" in _r.stdout and "body a" not in _r.stdout and "body b" not in _r.stdout, _r.stdout[-200:])
check("...and warns that several blocks claim to be current", "3 current pickup blocks" in _r.stdout)
check("...and labels itself RECORDED, not measured", "RECORDED, not measured" in _r.stdout)
check("...and carries none of the managed block's numbers", "W0M-STATE-DATA" not in _r.stdout)
_none = _pk / "STATE-nopickup.md"
_none.write_text(_head, encoding="utf-8")
_r = run(_none, "--brief")
check("--brief with NO pickup block exits non-zero", _r.returncode != 0, f"rc={_r.returncode}")
check("...and says so rather than printing an empty brief", "no current" in _r.stdout, _r.stdout[-200:])
_r = run(_pk / "absent.md", "--brief")
check("--brief on a MISSING file exits non-zero", _r.returncode != 0, f"rc={_r.returncode}")

print("\n── 🔴 T428 AC2: --write synthesizes the pickup block from ticket status notes ──")
from datetime import date as _dt_date
_today_str = _dt_date.today().isoformat()
(_pk / ".tasks" / "T904.md").write_text(
    f"---\nid: T904\ntitle: Just Finished\nstatus: done\n---\n\n## Status notes\n\n- {_today_str} — verified and closed\n", encoding="utf-8")
_wr_fix = _pk / "STATE-write.md"
_wr_fix.write_text(_head + "## ⭐ PICK UP HERE — 2026-08-10 — old\n\nold handoff\n", encoding="utf-8")
_r_wr = run(_wr_fix, "--write")
_written = _wr_fix.read_text(encoding="utf-8")
check("--write exits 0 on fixture with tickets", _r_wr.returncode == 0, (_r_wr.stdout + _r_wr.stderr)[-200:])
check("...replaces pickup block with generated heading carrying today's date",
      f"## ⭐ PICK UP HERE — {_today_str} (generated)" in _written, _written[:600])
check("...lists in-progress ticket with newest status note",
      "T901" in _written and "newest note wins" in _written)
check("...flags in-progress ticket without status notes",
      "T902" in _written and "NO status note recorded" in _written)
check("...includes ticket completed today under Completed today",
      "#### Completed today (1):" in _written and "T904" in _written and "verified and closed" in _written)
check("...leaves older completed tickets out of completed today",
      "T903" not in _written)

print("\n── the control: a file the tool itself just wrote must PASS ──")

good = TMP / "STATE.md"
shutil.copy(ROOT / "STATE.md", good)
# T174 — the fixture must carry the ARCHIVE + DISPOSITION alongside it, because `--check` now also
# verifies that every section has a recorded disposition. Without this the control would fail for a
# reason that has nothing to do with staleness, and every case below would be untrustworthy.
# (Both are resolved relative to the STATE.md being processed, which is what makes this possible —
# an earlier version anchored them at the repo root and a fixture run wrote 19 files into the tree.)
if (ROOT / "project" / "state-archive").is_dir():
    shutil.copytree(ROOT / "project" / "state-archive", TMP / "project" / "state-archive")
run(good, "--write")
r = run(good, "--check")
check("a freshly written STATE.md passes", r.returncode == 0, (r.stdout + r.stderr)[-200:])

# T174 §6.1 — the budget must be legible on the GREEN path, not only when it blocks. An agent
# about to write the next ⭐ block is the one who needs the number, and by the time
# `budget_problems` speaks the push is already rejected. Assert the real measurement is present,
# not merely the word "budget": a report that stops reporting is the failure worth catching.
out = r.stdout + r.stderr
live_lines = good.read_text().count("\n") + 1
check("the green path REPORTS budget usage, not just silence on pass",
      "lines (" in out and "bytes (" in out, out[-240:])
check("...and the reported line count is the measured one, not a stale constant",
      f"{live_lines:,}/" in out, f"expected {live_lines:,}/… in: {out[-240:]}")

print("\n── 🔴 the RED case AC9 demanded: a recorded exit code that lies ──")

lying = TMP / "lying.md"
text = good.read_text()
# Flip a recorded gate exit code in the W0M-STATE-DATA payload — the fact most likely to be
# silently wrong in a hand-maintained file, and the one the gate exists to catch.
mutated, n = re.subn(r'("gates":\s*\{[^}]*?"[a-z]+":\s*)(\d+)', lambda m: m.group(1) + ("9" if m.group(2) != "9" else "8"), text, count=1)
lying.write_text(mutated)
check("the fixture really was mutated", n == 1, f"substitutions={n}")

r = run(lying, "--check")
out = r.stdout + r.stderr
check("a lying gate exit code FAILS the check", r.returncode != 0, f"rc={r.returncode}")
check("...and the output names the gate and both values", "records exit" in out, out[-240:])

print("\n── absent or empty managed block must FAIL, not pass ──")

no_block = TMP / "no_block.md"
no_block.write_text("# STATE\n\nprose only, no managed block at all.\n")
r = run(no_block, "--check")
out = r.stdout + r.stderr
check("NO managed block fails", r.returncode != 0, f"rc={r.returncode}")
check("...and refuses to certify rather than reporting clean",
      "refusing" in out.lower() or "no managed block" in out.lower(), out[-200:])

empty_payload = TMP / "empty.md"
begin = [ln for ln in text.splitlines() if "W0M-STATE:BEGIN" in ln][0]
end = [ln for ln in text.splitlines() if "W0M-STATE:END" in ln][0]
empty_payload.write_text(f"# STATE\n\n{begin}\n\n(nothing here)\n\n{end}\n")
r = run(empty_payload, "--check")
out = r.stdout + r.stderr
check("a managed block with NO data payload fails", r.returncode != 0, f"rc={r.returncode}")
check("...and says the payload is unreadable rather than passing",
      "payload" in out.lower() or "refusing" in out.lower(), out[-200:])

print("\n── a missing file is not a clean bill of health ──")

r = run(TMP / "does-not-exist.md", "--check")
check("a MISSING STATE.md fails", r.returncode != 0, f"rc={r.returncode}")

# ══════════════════════════════════════════════════════════════════════════════
# T174 AC6 — the RETENTION gates. Same discipline, and it matters MORE here for one reason:
#
#   🔴 A retention gate's natural FAILURE mode — a small file — is indistinguishable from its
#      SUCCESS condition. "Under budget" is trivially true of an empty file, so a budget check that
#      only compares sizes certifies exactly the state it should refuse.
#
# That is the shape this estate has shipped FOUR times (T127's `0 managed … ✓`, T130's enforce_raw,
# T135's docs-check over an empty section list, the wom7md hook that did not exist). So every case
# below asserts what the gate must NOT accept, not just what it accepts.
# ══════════════════════════════════════════════════════════════════════════════

print("\n── 🔴 T174 AC6: the size budget must FAIL when exceeded ──")

fat = TMP / "fat.md"
# Grow the fixture past budget with content that is unmistakably filler, so a failure cannot be
# mistaken for a real drift finding.
fat.write_text(good.read_text() + "\n\n## filler\n" + ("padding line for the budget probe\n" * 4000))
r = run(fat, "--check")
out = r.stdout + r.stderr
check("an over-budget STATE.md FAILS", r.returncode != 0, f"rc={r.returncode}")
check("...and names the budget AND the measured value",
      "over the declared budget" in out and "state-rotate" in out, out[-260:])

print("\n── 🔴 T174 AC6: a nearly-empty file must NOT be certified as 'within budget' ──")

# The load-bearing case. This file is far UNDER every budget, and must still fail.
tiny = TMP / "tiny.md"
begin = [ln for ln in good.read_text().splitlines() if "W0M-STATE:BEGIN" in ln][0]
data = [ln for ln in good.read_text().splitlines() if "W0M-STATE-DATA" in ln][0]
end = [ln for ln in good.read_text().splitlines() if "W0M-STATE:END" in ln][0]
tiny.write_text(f"# STATE\n\n{begin}\n\n{data}\n{end}\n")
r = run(tiny, "--check")
out = r.stdout + r.stderr
check("a content-free STATE.md FAILS despite being tiny", r.returncode != 0, f"rc={r.returncode}")
check("...and says so rather than reporting 'within budget'",
      "no content outside the managed block" in out, out[-260:])

print("\n── 🔴 T174 AC2: a section with NO disposition row must FAIL ──")

orphan = TMP / "orphan.md"
orphan.write_text(good.read_text()
                  + "\n\n### 9z. a section nobody triaged — 2026-08-07\n\nunaccounted content.\n")
r = run(orphan, "--check")
out = r.stdout + r.stderr
check("an unaccounted section FAILS", r.returncode != 0, f"rc={r.returncode}")
check("...and refuses to default it to 'archived'",
      "NO disposition row" in out or "no disposition" in out.lower(), out[-260:])

print("\n── 🔴 T174 AC1: rotation over an empty candidate set is not a clean sweep ──")

# `good` is a copy of the LIVE STATE.md plus `--write` — it is not guaranteed to already be
# rotated, because writing a new pickup block is what supersedes the old one, and rotating it is a
# separate, deliberate step (T174's own docstring). Rotate `good` here first so it becomes what the
# case actually needs: the tool's OWN post-rotation output, with nothing left to move. Skipping
# this made the case depend on the live file happening to have no pending superseded pickup block
# at test time, which it is not obliged to.
run(good, "--rotate")
rot = TMP / "rot.md"
shutil.copy(good, rot)
r = run(rot, "--rotate")
out = r.stdout + r.stderr
check("rotation with nothing to move exits 0 (the idempotent case)", r.returncode == 0, f"rc={r.returncode}")
check("...and SAYS the candidate set was empty rather than implying a sweep",
      "candidate set was EMPTY" in out, out[-300:])
check("...and states the scope it examined", "section(s) examined against" in out, out[-300:])

print("\n── 🔴 T174 AC1: rotation refuses a missing or empty file ──")

r = run(TMP / "nope.md", "--rotate")
check("rotation on a MISSING file exits non-zero", r.returncode != 0, f"rc={r.returncode}")
check("...and refuses rather than reporting a clean rotation",
      "does not exist" in (r.stdout + r.stderr), (r.stdout + r.stderr)[-200:])

zero = TMP / "zero.md"
zero.write_text("")
r = run(zero, "--rotate")
out = r.stdout + r.stderr
check("rotation on a ZERO-BYTE file exits non-zero", r.returncode != 0, f"rc={r.returncode}")
check("...and names it as the vacuous case", "vacuous" in out or "is empty" in out, out[-200:])

print("\n── 🔴 T174 AC8: a malformed retention policy must NAME the bad key, not fall back ──")

import json as _json  # noqa: E402
bad_cfg_dir = TMP / "badcfg"
(bad_cfg_dir / ".w0m").mkdir(parents=True)
shutil.copy(ROOT / "STATE.md", bad_cfg_dir / "STATE.md")
