#!/usr/bin/env python3
"""Prove the decisions index refuses to lie — T232 AC8, T392 AC4.

The failure this guards against is not a wrong row, it is an EMPTY or STALE index that reads as
authoritative. Both are exercised here.
"""
from __future__ import annotations
import importlib.util, json, os, re, subprocess, sys, tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT_T = HERE.parent.parent
SCRIPT = HERE.parent / "decisions_index.py"
spec = importlib.util.spec_from_file_location("di", SCRIPT)
di = importlib.util.module_from_spec(spec)
spec.loader.exec_module(di)


class P:
    def __init__(self):
        self.n = 0
        self.fail: list[str] = []

    def check(self, label: str, ok: bool, detail: str = "") -> None:
        self.n += 1
        print(f"  {label:<62} {'ok' if ok else '!! FAILED'}")
        if not ok:
            self.fail.append(f"{label} {detail}".strip())


def main() -> int:
    p = P()
    rows = di.harvest()

    print("\nTHE SWEEP IS REAL")
    p.check("it finds decisions in the live corpus", len(rows) > 50, str(len(rows)))
    kinds = {r["kind"] for r in rows}
    p.check("...across MORE THAN ONE surface (not just tickets)", len(kinds) >= 4, str(kinds))
    p.check("every row names a file and a line",
            all(r["file"] and r["line"] for r in rows))
    p.check("dated rows carry a real ISO date",
            all(re.fullmatch(r"20\d{2}-\d{2}-\d{2}", r["date"]) for r in rows if r["date"]))

    print("\n🔴 AN EMPTY SWEEP FAILS RATHER THAN PUBLISHING AN EMPTY INDEX")
    src = SCRIPT.read_text()
    p.check("main() refuses on zero rows", "found ZERO decisions" in src)
    p.check("...and says the matcher broke, not that nobody decided",
            "not that nobody decided anything" in src)

    print("\n🔴 A STALE INDEX IS A FAILURE, NOT A WARNING")
    p.check("--check exists and exits non-zero on drift", "is STALE" in src)
    r = subprocess.run([sys.executable, str(SCRIPT), "--check"], capture_output=True, text=True,
                       cwd=str(ROOT_T))
    p.check("the committed index is CURRENT right now", r.returncode == 0,
            (r.stdout + r.stderr)[-160:])

    print("\nIT IS AN INDEX, NOT A STORE")
    body = di.render(rows)
    p.check("the page says it is generated", "GENERATED by `just decisions`" in body)
    p.check("...and that it is not the source of truth", "nothing here is the source of truth" in body)
    p.check("no decision TEXT is invented — every row quotes its line",
            all(r["text"] for r in rows))
    p.check("sources are an explicit list, not a glob over everything",
            isinstance(di.SOURCES, list) and len(di.SOURCES) >= 5)

    print("\n🔴 AgDR RECORDS ARE FIRST-CLASS, AND SUPERSESSION IS THE POINT")
    recs = di.agdr_records()
    p.check("at least one AgDR record exists", len(recs) >= 1, str(len(recs)))
    p.check("each carries id, agent and status",
            all(r["id"] and r["agent"] and r["status"] for r in recs))
    # `model` is required for an AGENT decision and meaningless for a human one
    p.check("model is present for every AGENT decision",
            all(r["model"] for r in recs if r["agent"] != "human"),
            str([r["id"] for r in recs if r["agent"] != "human" and not r["model"]]))
    p.check("...and human decisions are allowed to omit it",
            any(r["agent"] == "human" for r in recs))
    p.check("each carries a Y-statement, not just a title",
            all(len(r["text"]) > 40 for r in recs), str([r["text"][:40] for r in recs]))
    body = di.render(di.harvest() + recs)
    p.check("the index renders a structured-records table", "## Structured records (AgDR)" in body)
    p.check("...separate from the unstructured ones", "## Recorded in place (unstructured)" in body)

    # supersession is the field the format was adopted for — prove it RENDERS, on a copy.
    live = [r for r in recs if not r["superseded_by"].strip()]
    p.check("there is a non-superseded record to mutate", bool(live), str([r["id"] for r in recs]))
    target = live[0]
    src_file = ROOT_T / target["file"]
    keep = src_file.read_text(encoding="utf-8")
    try:
        src_file.write_text(keep.replace("superseded_by:", "superseded_by: AgDR-9999", 1), encoding="utf-8")
        out = di.render(di.harvest() + di.agdr_records())
        line = [l for l in out.splitlines() if l.startswith(f"| [`{target['id']}`]")]
        p.check("a superseded record is STRUCK THROUGH", bool(line) and "~~" in line[0])
        p.check("...and names its replacement", bool(line) and "AgDR-9999" in line[0])
        p.check("...and its status reads superseded", bool(line) and "superseded" in line[0])
    finally:
        src_file.write_text(keep, encoding="utf-8")
    out2 = di.render(di.harvest() + di.agdr_records())
    p.check("restoring clears the strike-through (no sticky state)",
            not any("~~" in l for l in out2.splitlines()
                    if l.startswith(f"| [`{target['id']}`]")))
    tmpl = ROOT_T / "project/templates/decision.md"
    p.check("the template exists and declares superseded_by", tmpl.exists()
            and "superseded_by" in tmpl.read_text())
    p.check("...and requires a trade-off in the Y-statement",
            "trade-off clause is not optional" in tmpl.read_text())

    # ── the pre-commit hook must cover every SOURCE the generator reads ──────────────────────
    cfg = (ROOT_T / ".pre-commit-config.yaml").read_text(encoding="utf-8")
    m = re.search(r"id: decisions-index-fresh[\s\S]*?files: (\S+)", cfg)
    p.check("the umbrella repo has a decisions-index-fresh hook", m is not None,
            "a source edited in the umbrella can shift every anchor; without this it fails the next deploy")
    if m:
        erx = re.compile(m.group(1))
        eentry = re.search(r"id: decisions-index-fresh[\s\S]*?entry: (.+)", cfg).group(1)
        p.check("...and it is CHECK-ONLY (cannot rewrite a file in a sibling repo)",
                "--check" in eentry and "git add" not in eentry)
        for path in [pat.replace("T*.md", "T204.md") for _, base, pat in di.SOURCES if base == di.ESTATE and not pat.startswith("w0m-web/")]:
            p.check(f"the umbrella hook fires on {path}", bool(erx.match(path)),
                    "a source the generator reads but the hook ignores goes stale silently")
        p.check("the umbrella hook fires on docs/decisions/AgDR-0001-test.md",
                bool(erx.match("docs/decisions/AgDR-0001-test.md")))
        for path in ["README.md", "scripts/tasks_query.py", ".tasks/archive/INDEX.md"]:
            p.check(f"...and does NOT fire on unrelated {path}", not erx.match(path),
                    "a filter that matches everything makes every commit pay for the check")

    # ── T392 AC4: AgDR CONVENTION TRACE ACROSS ALL ESTATE REPOS ─────────────────────────────
    print("\n🔴 T392 AC4: AgDR CONVENTION TRACE ACROSS ALL ESTATE REPOS")
    sdlc_file = ROOT_T / ".w0m/sdlc.json"
    p.check("sdlc.json exists", sdlc_file.is_file())
    sdlc = json.loads(sdlc_file.read_text(encoding="utf-8"))
    repos = sorted(set(sdlc.get("repos", {}).values()))

    # Check root AGENTS.md
    root_agents = ROOT_T / "AGENTS.md"
    p.check("root AGENTS.md exists", root_agents.is_file())
    root_txt = root_agents.read_text(encoding="utf-8")
    p.check("root AGENTS.md cites docs/DECISIONS.md and docs/decisions/",
            "docs/DECISIONS.md" in root_txt and "docs/decisions/" in root_txt)

    # Check each declared repo's AGENTS.md
    for repo in repos:
        rdir = ROOT_T / repo
        ragents = rdir / "AGENTS.md"
        p.check(f"{repo}/AGENTS.md exists", ragents.is_file())
        if ragents.is_file():
            rtxt = ragents.read_text(encoding="utf-8")
            p.check(f"{repo}/AGENTS.md states AgDR standard and points to decisions",
                    ("AgDR" in rtxt or "decisions" in rtxt.lower()) and "DECISIONS.md" in rtxt,
                    f"{repo}/AGENTS.md lacks AgDR / DECISIONS reference")

    print("\n" + "-" * 76)
    if p.fail:
        print(f"FAIL — {len(p.fail)} of {p.n}:", file=sys.stderr)
        for f in p.fail:
            print(f"  ✗ {f}", file=sys.stderr)
        return 1
    print(f"✅ {p.n} checks — the index cannot be empty, cannot go stale unnoticed, and never")
    print("   claims to be the decision itself.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
